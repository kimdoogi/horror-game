#!/usr/bin/env python3
"""Turns an AI-generated base sculpt into a shippable monster: mesh, rig, clips.

Run headless::

    /Applications/Blender.app/Contents/MacOS/Blender --background --factory-startup \\
        --python tools/blender/gen_monster_ai.py

Writes ``Assets/Models/Characters/Monster.fbx`` — **the creature the game loads** —
with ``Monster.glb``, ``Monster.clips.json`` and ``Assets/Textures/Monster.textures.json``
alongside it. Those four names are the whole contract: ``MonsterRig.cs`` and
``MonsterSkin.cs`` hardcode them, so this generator is now the one that feeds them and
``gen_monster_model.py`` no longer writes a shipping asset.

Add ``-- --vessel`` to also build the human-shaped variant. It is deliberately NOT
written into ``Assets/``: it goes to ``artifacts/monster_variants/`` so it can be
looked at without becoming a second monster nobody is sure about. See VARIANTS.

WHY THIS EXISTS ALONGSIDE gen_monster_model.py
----------------------------------------------
``gen_monster_model.py`` builds its monster out of convex hulls and tubes. That is
reproducible and cheap to retune, and it is why the asset shipped at all — but it
cannot make a concave form. No sunken flank, no hollow between two ribs, no socket
where an eye is missing. Everything it produces is an assembly of bulges, and past a
certain distance that is exactly what it reads as.

So the base shape here is not built, it is **imported**: a sculpt generated by
Hyper3D Rodin from a text description of §01/§06's creature, committed under
``tools/blender/source/`` because that generation is not reproducible. Everything
downstream of the sculpt *is* reproducible, and that is what this file is:

    sculpt → decimate to budget → measure → fit the 29-bone rig → skin →
    grade the textures to §03's albedo policy → author the seven §06 clips → export

WHAT THE SCULPT DOES NOT ARRIVE WITH, AND WHY IT IS ADDED HERE
--------------------------------------------------------------
Rodin returns one closed surface and one material. The game does not render "one
surface" — it renders three channels that three different pieces of code drive, and a
sculpt dropped in with its single ``Monster_Hide`` silently disconnects two of them:

* ``MonsterSkin.EyeGlow`` lights whatever material is called ``Monster_Eyes``. That
  pair of lenses is §04's entire 관측자 channel at 15 m, where the body is forty pixels
  of smudge and two separated points are the only thing that still reads as a *facing*.
  With one material there is nowhere to put it, and lighting the one material lights
  the whole creature — which is §03's lock on progress handed back to the player.
* ``MonsterAcquireTell`` lights whatever material is called ``Monster_Maw`` when §06
  enters 추격. On a one-material creature that write either does nothing or turns the
  whole animal into a lantern.

So this file grows the lenses (``add_eyes``, placed by ray-casting the sculpt's own
head) and splits out the maw (``maw_polygons``, taken as the faces the ``Jaw`` bone
actually moves). Both are *derived from the sculpt*, because the previous attempt at
eyes on the hull monster used hand-written coordinates, put one lens 15 cm inside the
head, and the only symptom was that a brightness sweep from 1.5 to 12 moved the
measured frame by 0.0003.

WHAT IS LOAD-BEARING, AND WHY IT IS NOT NEGOTIABLE
--------------------------------------------------
The rig is a contract with code that already exists, not a free choice:

* ``MonsterAcquireTell.cs`` rotates ``Crest1..3`` and ``Jaw`` — that is §06's Alert
  tell, the thing §04's 관측자 is supposed to read at range. Bones alone are not
  enough: a crest bone with no crest on it animates nothing anybody can see, so this
  generator **adds crest geometry** to the sculpt rather than dropping the bones.
* ``MonsterRig.cs`` masks the Locomotion layer by bone name, ``Hips`` included.
* ``AssetImportValidator.cs`` asserts the rig is Generic and carries ``Jaw``,
  ``Crest1..3``, ``LeftScapulaSpur`` and ``Left/RightForearmExtra``, with the forearm
  extras *inside* the arm chain (UpperArm → LowerArm → ForearmExtra → Hand).
* ``AssetImportPolicy.MonsterHeightMetres`` pins the height at 2.336 m.

All 29 bone names therefore survive verbatim. What changes is where they sit: they
are fitted to whatever the sculpt actually is, by ``monster_fit.measure``.

THE ALBEDO POLICY IS THE OTHER CONTRACT
---------------------------------------
``Monster.textures.json`` records the rule the previous asset was tuned to, and it is
the least obvious and most important number here: the hide's mean albedo is **0.17
linear, deliberately under the 0.21 of the darkest wall in a §12 corridor**. A
creature brighter than its corridor announces itself, and §06 depends on you noticing
it too late. Rodin returns a sculpt lit for a turntable — bright, mid-grey, made to
look good on a white background. Shipping that unchanged would undo the whole policy,
so the maps are re-graded here and the result is asserted, not hoped for.
"""

