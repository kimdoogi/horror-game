def load_base(path: str) -> bpy.types.Object:
    """Imports the sculpt, drops the importer's debris and normalises the transform.

    glTF import leaves a bone-display icosphere behind and parents the mesh under an
    empty. Both are stripped so what comes back is a single mesh at the origin with
    an identity matrix — every measurement downstream assumes that.
    """
    before = set(bpy.data.objects)
    bpy.ops.import_scene.gltf(filepath=path)
    added = [o for o in bpy.data.objects if o not in before]

    meshes = [o for o in added if o.type == "MESH" and not o.name.startswith("Icosphere")]
    if not meshes:
        blendkit.fail(f"{os.path.basename(path)} contains no mesh")
    obj = max(meshes, key=lambda o: len(o.data.vertices))

    for junk in added:
        if junk is not obj:
            bpy.data.objects.remove(junk, do_unlink=True)

    obj.matrix_world = Matrix.Identity(4)
    obj.parent = None
    return obj


def normalise(obj: bpy.types.Object) -> float:
    """Scales to the pinned height and plants the sculpt at the origin, feet on Z=0.

    Returns the scale factor it applied, so a caller that measured the mesh before a
    later normalise can bring its measurements forward.

    Works on mesh data rather than the object transform on purpose: ``transform_apply``
    is an operator, and operators silently do nothing when the context has no 3D view —
    which is exactly the case under ``--background``. A scale that quietly failed to
    apply would leave the asset at Rodin's normalised size and every measurement here
    would then be taken in the wrong units.
    """
    me = obj.data

    def bounds():
        lo = Vector((1e9,) * 3)
        hi = Vector((-1e9,) * 3)
        for v in me.vertices:
            for i in range(3):
                lo[i] = min(lo[i], v.co[i])
                hi[i] = max(hi[i], v.co[i])
        return lo, hi

    lo, hi = bounds()
    span = hi - lo
    if span.z < max(span.x, span.y):
        # Rodin returns Y-up. Everything here is Z-up, so stand it up first.
        me.transform(Matrix.Rotation(math.radians(90.0), 4, "X"))
        lo, hi = bounds()

    scale = TARGET_HEIGHT / (hi.z - lo.z)
    me.transform(Matrix.Scale(scale, 4))
    lo, hi = bounds()
    me.transform(Matrix.Translation(Vector((-(lo.x + hi.x) / 2.0,
                                            -(lo.y + hi.y) / 2.0,
                                            -lo.z))))
    me.update()
    return scale


def mesh_bounds(obj: bpy.types.Object) -> tuple[Vector, Vector]:
    """World-space bounds of what will actually be exported.

    The size assertions run off this rather than off the landmark dict. The landmarks
    are measured before decimation and before the crest is welded on, so they describe
    the sculpt that was analysed, not the asset that ships — and the height they carry
    would pass a check the exported mesh fails.
    """
    lo = Vector((1e9,) * 3)
    hi = Vector((-1e9,) * 3)
    for v in obj.data.vertices:
        w = obj.matrix_world @ v.co
        for i in range(3):
            lo[i] = min(lo[i], w[i])
            hi[i] = max(hi[i], w[i])
    return lo, hi


def triangles(obj: bpy.types.Object) -> int:
    obj.data.calc_loop_triangles()
    return len(obj.data.loop_triangles)


def decimate(obj: bpy.types.Object, target: int) -> None:
    """Collapses the sculpt down to the triangle budget, keeping the UV layout.

    Collapse rather than un-subdivide or planar: it is the only mode that treats the
    silhouette as the thing worth spending vertices on, and the silhouette is all this
    asset has in a dark corridor. UVs survive because Rodin's maps are baked to them —
    losing them would mean re-unwrapping and re-baking a sculpt this file did not make.
    """
    have = triangles(obj)
    if have <= target:
        return
    mod = obj.modifiers.new("Budget", "DECIMATE")
    mod.decimate_type = "COLLAPSE"
    mod.ratio = target / have
    mod.use_collapse_triangulate = True

    depsgraph = bpy.context.evaluated_depsgraph_get()
    baked = bpy.data.meshes.new_from_object(obj.evaluated_get(depsgraph))
    old = obj.data
    obj.data = baked
    obj.modifiers.remove(mod)
    bpy.data.meshes.remove(old)


# ── Rig ─────────────────────────────────────────────────────────────────────


def _lerp(a, b, t):
    return a + (b - a) * t


def _p(x, y, z):
    return (float(x), float(y), float(z))


def fit_bones(m: dict) -> list[BoneSpec]:
    """Places the 29 contractual bones on whatever the sculpt turned out to be.

    Every height comes from ``monster_fit.measure``; nothing is a fraction of the
    total height, because the two sculpts have genuinely different proportions — the
    creature's crotch sits 19 cm higher than the vessel's on the same 2.336 m frame,
    and a ratio tuned to either one dislocates the other.

    The four-segment arm is the one place geometry is invented rather than measured.
    ``AssetImportValidator`` requires ForearmExtra *inside* the chain, and a sculpt has
    one forearm, so the forearm is split in half: LowerArm takes the upper half,
    ForearmExtra the lower. Both lie along real geometry, which is what auto-weights
    need; the extra joint is free to bend where a person's cannot, which is the point.
    """
    crotch = m["crotch"]
    shoulder = m["shoulder"]
    neck = m["neck"]
    top = m["top"]
    height = m["height"]

    # The hip pivot rides above the crotch — that is where a femur head actually sits,
    # and putting Hips on the crotch itself makes the pelvis collapse when it rotates.
    hips_z = crotch + (shoulder - crotch) * 0.11
    chest_z = _lerp(hips_z, shoulder, 0.52)
    upper_chest_z = _lerp(hips_z, shoulder, 0.80)
    spine_z = _lerp(hips_z, chest_z, 0.45)
    head_z = _lerp(neck, top, 0.35)

    back = m["back_y"]
    front = m["front_y"]

    specs = [
        BoneSpec("Hips", _p(0, 0, hips_z), _p(0, 0, hips_z + height * 0.04)),
        BoneSpec("Spine", _p(0, 0, spine_z), _p(0, 0, chest_z), "Hips"),
        BoneSpec("Chest", _p(0, 0, chest_z), _p(0, 0, upper_chest_z), "Spine", True),
        BoneSpec("UpperChest", _p(0, 0, upper_chest_z), _p(0, 0, neck), "Chest", True),
        BoneSpec("Neck", _p(0, 0, neck), _p(0, m["head_y"] * 0.5, head_z), "UpperChest"),
        BoneSpec("Head", _p(0, m["head_y"] * 0.5, head_z), _p(0, m["head_y"], top), "Neck", True),
        # Points down and forward, so swinging it forward gapes the maw rather than
        # dropping a chin — the sculpt has no hinge, so the bone supplies the motion.
        BoneSpec("Jaw", _p(0, m["head_y"] * 0.8, head_z),
                 _p(0, front * 0.5, _lerp(neck, head_z, 0.15)), "Head"),
    ]

    # The dorsal crest: three chained blades rising off the back above the shoulders.
    # Their geometry is added by `add_crest`, which reads these same numbers.
    # Rooted between the shoulder blades, not on the skull. Run up by the head and the
    # fan ends up beside it, where the skull hides most of it from the front — and the
    # front is where §06 has the creature coming at you. From the upper back it clears
    # the silhouette on every side.
    c0 = (0.0, back * 0.70, _lerp(chest_z, upper_chest_z, 0.35))
    c1 = (0.0, back * 1.00, upper_chest_z + (neck - upper_chest_z) * 0.45)
    c2 = (0.0, back * 1.12, _lerp(neck, top, 0.18))
    c3 = (0.0, back * 1.18, _lerp(neck, top, 0.44))
    specs += [
        BoneSpec("Crest1", _p(*c0), _p(*c1), "UpperChest"),
        BoneSpec("Crest2", _p(*c1), _p(*c2), "Crest1", True),
        BoneSpec("Crest3", _p(*c2), _p(*c3), "Crest2", True),
        BoneSpec("LeftScapulaSpur",
                 _p(m["arm_x_shoulder"] * 0.62, back * 0.35, shoulder - height * 0.02),
                 _p(m["arm_x_shoulder"] * 0.95, back * 0.95, shoulder + height * 0.06),
                 "UpperChest"),
    ]

    elbow, wrist, tip = m["elbow"], m["wrist"], m["fingertip"]
    mid_forearm = _lerp(elbow, wrist, 0.5)
    ax_sh, ax_el, ax_wr = m["arm_x_shoulder"], m["arm_x_elbow"], m["arm_x_wrist"]
    ay_sh, ay_wr = m["arm_y_shoulder"], m["arm_y_wrist"]
    ax_mid = _lerp(ax_el, ax_wr, 0.5)

    knee, ankle = m["knee"], m["ankle"]
    lx_hip, lx_knee, lx_ank = m["leg_x_hip"], m["leg_x_knee"], m["leg_x_ankle"]
    heel_y, toe_y = m["heel_y"], m["toe_y"]
    ankle_y = _lerp(heel_y, toe_y, 0.32)
    ball_y = _lerp(heel_y, toe_y, 0.82)

    for side in (1, -1):
        s = "Left" if side > 0 else "Right"
        x = float(side)
        specs += [
            BoneSpec(f"{s}Shoulder", _p(x * ax_sh * 0.24, 0.0, shoulder),
                     _p(x * ax_sh, ay_sh, shoulder), "UpperChest"),
            BoneSpec(f"{s}UpperArm", _p(x * ax_sh, ay_sh, shoulder),
                     _p(x * ax_el, _lerp(ay_sh, ay_wr, 0.5), elbow), f"{s}Shoulder", True),
            BoneSpec(f"{s}LowerArm", _p(x * ax_el, _lerp(ay_sh, ay_wr, 0.5), elbow),
                     _p(x * ax_mid, _lerp(ay_sh, ay_wr, 0.75), mid_forearm),
                     f"{s}UpperArm", True),
            BoneSpec(f"{s}ForearmExtra",
                     _p(x * ax_mid, _lerp(ay_sh, ay_wr, 0.75), mid_forearm),
                     _p(x * ax_wr, ay_wr, wrist), f"{s}LowerArm", True),
            BoneSpec(f"{s}Hand", _p(x * ax_wr, ay_wr, wrist),
                     _p(x * ax_wr, ay_wr, tip), f"{s}ForearmExtra", True),
            BoneSpec(f"{s}UpperLeg", _p(x * lx_hip, 0.0, hips_z),
                     _p(x * lx_knee, 0.0, knee), "Hips"),
            BoneSpec(f"{s}LowerLeg", _p(x * lx_knee, 0.0, knee),
                     _p(x * lx_ank, ankle_y, ankle), f"{s}UpperLeg", True),
            BoneSpec(f"{s}Foot", _p(x * lx_ank, ankle_y, ankle),
                     _p(x * lx_ank, ball_y, ankle * 0.22), f"{s}LowerLeg", True),
            BoneSpec(f"{s}Toes", _p(x * lx_ank, ball_y, ankle * 0.22),
                     _p(x * lx_ank, toe_y, ankle * 0.10), f"{s}Foot", True),
        ]
    return specs


def add_crest(obj: bpy.types.Object, m: dict, specs: list[BoneSpec]) -> list[tuple]:
    """Grows a dorsal crest along the Crest1..3 bones and welds it onto the sculpt.

    §06's Alert state is the only moment the creature shows intent, and
    ``MonsterAcquireTell.cs`` shows it by flaring these three bones. A sculpt has no
    crest, so animating those bones would move nothing — the tell would exist in code
    and be invisible in play, which is worse than not having one, because the design
    then believes the player was warned.

    Built as a fan rather than a single fin: a fin disappears at the yaw the player
    almost always sees the creature from, and a tell nobody can see is decoration.
    Returns the (vertex-range, bone) pairs so the caller can weight them rigidly —
    auto-weights would bleed the crest onto the spine and it would stop reading.
    """
    by_name = {s.name: s for s in specs}
    me = obj.data
    ranges = []

    bm = bmesh.new()
    bm.from_mesh(me)
    bm.verts.ensure_lookup_table()

    # Anchored to the sculpt's actual back, sampled per height. Placing the blades at
    # a fraction of the torso's deepest point instead put them in mid-air behind the
    # neck — the back tapers between the shoulders and the skull, so one number taken
    # at the ribcage does not describe it. A crest that does not touch the creature
    # reads as a prop lying on it.
    verts_world = [obj.matrix_world @ v.co for v in obj.data.vertices]
    unit = m["height"]

    def back_at(z):
        band = [c.y for c in verts_world
                if abs(c.z - z) < unit * 0.035 and abs(c.x) < unit * 0.05]
        return max(band) if band else m["back_y"]

    for idx, name in enumerate(("Crest1", "Crest2", "Crest3")):
        spec = by_name[name]
        head, tail = Vector(spec.head), Vector(spec.tail)
        if (tail - head).length < 1e-6:
            continue
        y_base = back_at(head.z)
        y_tip = back_at(tail.z)
        inset = unit * 0.035        # how far the root is buried, so it never floats
        chord = unit * (0.105 - 0.022 * idx)
        reach = unit * (0.090 - 0.018 * idx)
        thick = unit * (0.013 - 0.002 * idx)
        start = len(bm.verts)

        # A centre blade plus one to each side of the lower two segments. A fan keeps
        # a readable outline at any yaw; a single fin vanishes when seen side-on, and
        # §04's 관측자 has to read this flare from wherever they happen to stand.
        blades = [(0.0, 1.0)] if idx == 2 else [(0.0, 1.0),
                                                (-unit * 0.048, 0.66),
                                                (unit * 0.048, 0.66)]
        for dx, scale in blades:
            t = thick * scale
            for sx in (-1.0, 1.0):
                ax = dx + sx * t
                bm.verts.new(Vector((ax, y_base - inset, head.z - unit * 0.012)))
                bm.verts.new(Vector((ax, y_base + chord * 0.55 * scale, head.z)))
                bm.verts.new(Vector((ax * 0.55,
                                     y_tip + reach * scale,
                                     head.z + (tail.z - head.z) * scale)))
        bm.verts.ensure_lookup_table()
        new = bm.verts[start:]
        if len(new) >= 4:
            bmesh.ops.convex_hull(bm, input=new)
        bm.verts.ensure_lookup_table()
        ranges.append((start, len(bm.verts), name))

    bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
    bm.to_mesh(me)
    bm.free()
    me.update()
    return ranges


def add_eyes(obj: bpy.types.Object, m: dict) -> list[tuple]:
    """Grows the asymmetric lens pair on the front of the sculpt's head and welds it on.

    The pair is the whole of §04's channel at range. ``MonsterSkin.EyeGlow``'s own note
    puts it plainly: at ``GameConstants.ObserverRange`` the creature is about forty
    pixels tall, the crest is four of them, and two separated points are the only thing
    left that says both *there is something there* and *it is facing you*. §12 obliges
    every zone to hold 관측 지점 that make that readable at 15 m and says that without
    them 관측자는 죽으러 가야 한다, so this is a mechanic, not a highlight.

    The pair is UNEQUAL on purpose — a hooded socket sunk into the creature's left,
    a hot pinpoint bead on its right, staggered in height. Two equal round lenses at
    one height on a smooth skull was the 2026-08 shot review's first finding: it
    reads as a cartoon robot. §04 keeps its two points; what dies is the symmetry.

    **Found, never typed.** The same rule ``gen_monster_model.build_eyes_on`` arrived at
    the hard way, applied to a surface this file did not author. A ray is cast from in
    front of the creature at every candidate (height, x) across the head, and a hit only
    counts when the surface it lands on is actually facing the player — ``ray_cast``
    returns the frontmost surface, so that one test rejects the back of the skull, the
    inside of the mouth and anything the snout occludes. Each lens is then built at an
    authored depth against whatever surface its ray actually hit.

    **What "the best place" means, measured.** The hull generator took the widest hit
    that faced forward at all, and on two flat head blades that was the right answer. On
    a smooth ovoid skull it is not: the widest forward-facing point is where the surface
    has turned almost edge-on, and the first render put both lenses on the *sides* of the
    head, reading as a pair of ears. Both of the things §04 needs are being traded here —
    separation carries *which way it is looking*, and facing carries *whether you can see
    the lens at all*, since a lens on a surface tilted by θ presents cos θ of its area.
    So the score is ``x · (n · view)``, their product, maximised over every candidate.
    On a sphere that lands at 45°, which is unambiguously on the face and still near the
    edge of it; on a flat-faced sculpt it walks straight back out to the corner.

    Re-sculpt the head, or change the decimation ratio, and the eyes move onto the new
    surface instead of ending up inside it. The alternative was tried on the previous
    asset: a hand-picked coordinate put a lens 15 cm inside a 0.66 m deep head, the
    creature shipped with two slivers of glass peeping out of a solid wedge, and the
    only symptom was that sweeping the eye brightness from 1.5 to 12 moved the measured
    frame by 0.0003.

    Returns two lists of ``(start, end, bone)`` vertex ranges — the lenses, then the
    brow hood — so the caller can weight them rigidly to the head (proximity weighting
    would share a lens between Head and Jaw and the gape would tear it in half) and
    put only the lenses on the eye material.
    """
    depsgraph = bpy.context.evaluated_depsgraph_get()
    evaluated = obj.evaluated_get(depsgraph)

    # The sculpt faces -Y (monster_fit's `front_y` is a minimum), so the player stands
    # at -Y and the probe travels +Y into the face.
    forward = Vector((0.0, -1.0, 0.0))
    neck, top = m["neck"], m["top"]
    unit = m["height"]

    head = [obj.matrix_world @ v.co for v in obj.data.vertices if (obj.matrix_world @ v.co).z >= neck]
    if not head:
        blendkit.fail("no geometry above the measured neck — there is no head to put eyes on")
    half_width = max(abs(c.x) for c in head)
    start_y = min(c.y for c in head) - unit * 0.25      # clear of the frontmost point

    def probe(z, x):
        """Frontmost forward-facing surface at (x, z) and how squarely it faces, or None."""
        hit, location, normal, _ = evaluated.ray_cast(
            Vector((x, start_y, z)), -forward, distance=unit * 1.2)
        # 0.15 is gen_monster_model's threshold: enough of the normal pointing at the
        # camera that a lens set into it is seen, not seen edge-on.
        facing = normal.dot(forward) if hit else 0.0
        return (location, facing) if hit and facing > 0.15 else None

    step_x = unit * 0.004

    def search(lo_z: float, hi_z: float):
        step_z = max(unit * 0.004, (hi_z - lo_z) / 48.0)
        found_best = None
        z = lo_z
        while z <= hi_z:
            pair, score = [], 0.0
            for side in (1, -1):
                x, found, mark = unit * 0.010, None, 0.0
                while x <= half_width * 0.99:
                    probed = probe(z, side * x)
                    if probed is not None and x * probed[1] > mark:
                        found, mark = probed[0], x * probed[1]
                    x += step_x
                pair.append(found)
                score += mark

            if all(p is not None for p in pair) and (found_best is None
                                                     or score > found_best[0]):
                found_best = (score, z, pair)
            z += step_z
        return found_best

    # A face band, not the whole skull. The unrestricted search maximises x·facing and
    # on an ovoid skull that lands near the crown — the shot review's frog eyes. The
    # band is where a face's eye line actually sits, above the jaw (a lens on the jaw
    # is an eye that opens when the creature roars) and decisively below the crown.
    # The wide band is kept as a fallback so a re-sculpt whose face band is all snout
    # degrades to the old placement instead of failing the build.
    best = search(neck + (top - neck) * 0.30, neck + (top - neck) * 0.62)
    if best is None:
        best = search(neck + (top - neck) * 0.32, top - (top - neck) * 0.06)

    if best is None:
        blendkit.fail(
            "no forward-facing surface anywhere on the head to sit a pair of lenses on. §04's "
            "관측자 reads the creature's facing off the pair and §12 obliges every zone to hold "
            "관측 지점 that make that readable at 15 m; a head with nowhere to put them is a head "
            "that has to be re-sculpted, not shipped.")
        return [], []

    score, z, pair = best
    separation = abs(pair[0].x - pair[1].x)

    # Two lenses that have merged into one point carry no facing at all, which is half
    # of what the pair exists for.
    if separation < EYE_MERGE_MIN:
        blendkit.fail(f"the widest forward-facing pair on this head is {separation * 100:.1f} cm "
                      f"apart, which at ObserverRange merges into a single point — and the point "
                      f"of two lenses is the facing, not the glow.")

    me = obj.data
    bm = bmesh.new()
    bm.from_mesh(me)
    bm.verts.ensure_lookup_table()

    def hull_range(pts: list[Vector], bone: str, out: list[tuple]) -> None:
        start = len(bm.verts)
        for p in pts:
            bm.verts.new(p)
        bm.verts.ensure_lookup_table()
        if len(bm.verts) - start >= 4:
            bmesh.ops.convex_hull(bm, input=bm.verts[start:])
        bm.verts.ensure_lookup_table()
        out.append((start, len(bm.verts), bone))

    ranges: list[tuple] = []
    extra: list[tuple] = []
    left, right = pair          # pair[0] is +X — the creature's left

    # ── The socket: creature's left. A larger cap SUNK into the face and hooded. ──
    # Sunk 4.5 mm, so only a shallow sliver of lens breaks the surface — the glow
    # arrives dim and edge-broken. Raised 16 mm off the shared eye line, because two
    # eyes at one height is the symmetry being killed. Deliberate millimetres, not
    # the hand-typed-coordinate failure the docstring above recounts: the position
    # still comes from the ray hit; only the depth and stagger are authored.
    centre = left + forward * (-0.0045)
    centre.z += 0.016
    pts = []
    for i in range(8):
        angle = i * math.pi / 4.0
        pts.append(Vector((centre.x + SOCKET_RADIUS * math.cos(angle),
                           centre.y + 0.004,
                           centre.z + SOCKET_RADIUS * 0.92 * math.sin(angle))))
        pts.append(Vector((centre.x + SOCKET_RADIUS * 0.55 * math.cos(angle),
                           centre.y - 0.004,
                           centre.z + SOCKET_RADIUS * 0.50 * math.sin(angle))))
    pts.append(Vector((centre.x, centre.y - 0.007, centre.z)))
    hull_range(pts, "Head", ranges)

    # The hood: a brow of hide drooping over the socket's upper half, running out
    # into a broken spur past the skull's outline. The spur is what puts a wound in
    # the head's FRONT silhouette — the sockets vanish in black-on-white, and a dead
    # human dome up top was the last thing on this creature a runner could be
    # mistaken for. On the hide material and returned separately, so it is welded,
    # weighted to Head and unwrapped like the crest but never lights up.
    pts = []
    for k in range(5):
        angle = math.pi * (0.15 + 0.70 * k / 4.0)
        hx = centre.x + math.cos(angle) * (SOCKET_RADIUS + 0.012)
        hz = centre.z + math.sin(angle) * (SOCKET_RADIUS + 0.010)
        pts.append(Vector((hx, left.y + 0.006, hz + 0.004)))
        pts.append(Vector((hx, left.y - 0.020, hz - 0.007)))
    for dx, dy, dz in ((0.052, -0.004, 0.030), (0.066, 0.004, 0.044),
                      (0.058, 0.014, 0.052)):
        pts.append(Vector((centre.x + dx, left.y + dy, centre.z + dz)))
    hull_range(pts, "Head", extra)

    # ── The pinpoint: creature's right. A bead, barely proud, dropped 12 mm. ──
    # Small is what makes it hot: the same EyeGlow through a tenth of the area reads
    # as a point of heat rather than a lamp.
    centre = right + forward * 0.008
    centre.z -= 0.012
    pts = []
    for i in range(8):
        angle = i * math.pi / 4.0
        pts.append(Vector((centre.x + PIN_RADIUS * math.cos(angle),
                           centre.y + 0.004,
                           centre.z + PIN_RADIUS * 0.90 * math.sin(angle))))
    pts.append(Vector((centre.x, centre.y - 0.008, centre.z)))
    pts.append(Vector((centre.x, centre.y + 0.010, centre.z)))
    hull_range(pts, "Head", ranges)

    bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
    bm.to_mesh(me)
    bm.free()
    me.update()

    print(f"EYES {obj.name} z={z:.3f} separation={separation:.3f} m "
          f"socket=+X r={SOCKET_RADIUS} pin=-X r={PIN_RADIUS}")
    return ranges, extra


def project_uvs(obj: bpy.types.Object, ranges: list[tuple], density: float) -> None:
    """Gives added geometry a planar X–Z unwrap at the body's own UV density.

    Density rather than "fill the 0–1 square", and that is the load-bearing part.
    ``MonsterSkin.ApplyTiling`` turns each material's declared ``world_size_metres``
    into a texture scale using one measured number — the whole mesh's UV units per
    metre — so a patch unwrapped at a different density samples its map at a different
    physical size than the manifest claims. Matching the body's density means the
    procedural maps land at exactly the centimetres they were drawn for, with nothing
    dialled in.
    """
    me = obj.data
    layer = me.uv_layers.active
    if layer is None:
        blendkit.fail("the sculpt has no UV layer — the maps would sample garbage")

    marked = set()
    for start, end, _ in ranges:
        marked.update(range(start, end))

    for poly in me.polygons:
        if not all(me.loops[i].vertex_index in marked for i in poly.loop_indices):
            continue
        for i in poly.loop_indices:
            co = me.vertices[me.loops[i].vertex_index].co
            layer.data[i].uv = (0.5 + co.x * density, 0.5 + co.z * density)


def maw_polygons(obj: bpy.types.Object) -> list[int]:
    """The faces the ``Jaw`` bone moves — which is exactly what §06's tell should light.

    ``MonsterAcquireTell`` gapes the mandible and lights ``Monster_Maw`` together, over
    the same 1.65 s, because the two are one event: the creature opening its mouth at
    you. Defining the maw as "whatever the Jaw bone owns" makes that true by
    construction on any sculpt — the lit region and the moving region are the same
    vertices, so the glow cannot end up on a cheek while the mouth opens elsewhere.

    A face belongs to the Jaw when the Jaw carries more than half of its corners'
    weight — a clear majority, not merely the largest of four influences. The margin
    matters: ``skin_by_proximity`` keeps four influences per vertex, so "the biggest
    share" can be 0.3 against 0.28, and taking that took a sixth of the creature. What
    is wanted is the part that visibly *swings* when the mandible drops.
    """
    me = obj.data
    jaw = obj.vertex_groups.get("Jaw")
    if jaw is None:
        blendkit.fail("the rig has no Jaw group, so §06's acquisition tell has nothing to light")
        return []

    index = jaw.index
    weight = [0.0] * len(me.vertices)
    for v in me.vertices:
        for g in v.groups:
            if g.group == index:
                weight[v.index] = g.weight

    faces = []
    for poly in me.polygons:
        verts = [me.loops[i].vertex_index for i in poly.loop_indices]
        if sum(weight[v] for v in verts) / len(verts) > 0.5:
            faces.append(poly.index)

    share = len(faces) / max(1, len(me.polygons))
    # Bounded from both ends because both failures are silent. Nothing, and §06's most
    # consequential transition has no visual at all; a third of the creature, and
    # entering 추격 turns the antagonist into a lamp — §03's darkness is the lock on
    # progress and the monster is not allowed to carry the key.
    if not 0.002 <= share <= 0.06:
        blendkit.fail(f"the Jaw owns {share * 100:.1f}% of the mesh's faces. Under 0.2% is a maw "
                      f"nobody can see light up; over 6% is a creature that becomes a lantern "
                      f"the moment §06 enters 추격.")
    print(f"MAW  {obj.name} {len(faces)} face(s), {share * 100:.2f}% of the mesh")
    return faces


def _segment_distance(p: Vector, a: Vector, b: Vector) -> float:
    ab = b - a
    denom = ab.length_squared
    if denom < 1e-12:
        return (p - a).length
    t = max(0.0, min(1.0, (p - a).dot(ab) / denom))
    return (p - (a + ab * t)).length


def skin_by_proximity(obj: bpy.types.Object, arm_obj: bpy.types.Object,
                      specs: list[BoneSpec], influences: int = 4) -> None:
    """Weights every vertex to its nearest bones, computed here rather than by Blender.

    ``bpy.ops.object.parent_set(type="ARMATURE_AUTO")`` is an operator, and operators
    need a context this process does not have under ``--background``. It does not
    raise — it returns and leaves the mesh unskinned, which is invisible until the
    export, where glTF invents a ``neutral_bone`` to hold the orphans. Measured on the
    first build: **8,215 of 8,291 vertices** ended up on that bone, so every clip
    played and nothing moved.

    So: distance from the vertex to each bone's segment, inverse-distance weighting
    with a sharp exponent, top `influences` kept and normalised. Two rules stop the
    obvious failures —

    * a vertex clearly on one side of the body cannot be weighted to the other side's
      limb bones, or a thigh picks up the opposite leg and the walk tears the pelvis;
    * the crest bones are excluded here and assigned explicitly afterwards, because
      their blades sit right beside the neck and would otherwise be captured by it.
    """
    by_name = {s.name: s for s in specs}
    limb_side = {}
    for name in by_name:
        if name.startswith("Left"):
            limb_side[name] = 1
        elif name.startswith("Right"):
            limb_side[name] = -1

    segments = []
    for s in specs:
        if s.name.startswith("Crest"):
            continue
        segments.append((s.name, Vector(s.head), Vector(s.tail), limb_side.get(s.name, 0)))

    groups = {name: obj.vertex_groups.new(name=name) for name, _, _, _ in segments}

    lo, hi = mesh_bounds(obj)
    half_width = max(1e-6, (hi.x - lo.x) * 0.5)
    # Far enough off the centreline that the limbs are unambiguous, close enough that
    # the torso still draws from both sides.
    side_cut = half_width * 0.22

    for v in obj.data.vertices:
        p = obj.matrix_world @ v.co
        side = 1 if p.x > side_cut else (-1 if p.x < -side_cut else 0)

        scored = []
        for name, head, tail, bone_side in segments:
            if side and bone_side and bone_side != side:
                continue
            d = _segment_distance(p, head, tail)
            scored.append((1.0 / (d + 0.012) ** 4, name))
        if not scored:
            continue
        scored.sort(reverse=True)
        top = scored[:influences]
        total = sum(w for w, _ in top)
        for w, name in top:
            groups[name].add([v.index], w / total, "REPLACE")


def build_rig(obj: bpy.types.Object, m: dict, want_crest: bool) -> tuple:
    """Fits the rig, welds on the crest and the lenses, and skins the lot.

    Returns the armature and the two sets of invented vertex ranges. The caller needs
    the crest's to unwrap it and the lenses' to unwrap them *and* to put them on their
    own material slot.
    """
    import gen_monster_model as gmm  # noqa: PLC0415

    specs = fit_bones(m)
    crest_ranges = add_crest(obj, m, specs) if want_crest else []
    # The pelvis shroud rides with the crest ranges: same rigid weighting, same
    # planar unwrap, same hide material — only the bone differs (Hips).
    crest_ranges += gmm.grow_pelvis_shroud(obj, m)
    # After the crest and before the armature modifier, so the ray-cast sees the final
    # exported surface and nothing posed. A lens placed against the rest sculpt and
    # then re-evaluated under a modifier would sit where the head used to be.
    eye_ranges, hood_ranges = add_eyes(obj, m)
    crest_ranges += hood_ranges

    arm_obj = blendkit.build_armature("Monster_Rig", specs)
    obj.parent = arm_obj
    obj.matrix_parent_inverse = arm_obj.matrix_world.inverted()
    mod = obj.modifiers.new("Armature", "ARMATURE")
    mod.object = arm_obj
    skin_by_proximity(obj, arm_obj, specs)

    # Auto-weights treat the crest as part of whatever spine segment it grew out of,
    # so it bends with the back and never flares. Overwrite those vertices outright.
    for name in ("Crest1", "Crest2", "Crest3"):
        if name not in obj.vertex_groups:
            obj.vertex_groups.new(name=name)

    # The lenses go on the same treatment for a different reason: a lens sits directly
    # above the Jaw's segment as well as the Head's, so proximity weighting splits it
    # between the two and the gape tears the eye in half down the middle.
    for start, end, name in crest_ranges + eye_ranges:
        idx = list(range(start, end))
        for group in obj.vertex_groups:
            group.remove(idx)
        obj.vertex_groups[name].add(idx, 1.0, "REPLACE")

    return arm_obj, crest_ranges, eye_ranges


