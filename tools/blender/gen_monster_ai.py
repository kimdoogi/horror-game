def build_eye_textures() -> dict:
    """Emits the lens's map set through the project's own procedural pipeline.

    Not graded from the sculpt, because the sculpt has no lenses — they were grown here.
    ``gen_monster_model.build_eyes`` already paints exactly this surface and its note
    argues the shape out: near-black wet glass, featureless at the distance that
    matters, with fine crazing that only exists to give §03's beam something to catch at
    3 m. It goes through the same ``write_skin`` every other surface in the game does,
    so the lens is held to ``gen_textures.py``'s albedo band and to the corridor ceiling
    by the same assertions, rather than being a colour this file picked.

    Always into ``Assets/Textures/Monster_Eyes/``, including on a variant that does not
    ship, and that is not an oversight: it is the same lens on either sculpt, painted
    from fixed seeds, so the bytes are identical whoever asked for them.
    """
    import gen_monster_model as gmm  # noqa: PLC0415

    # 1024, not TEX_RES: the 2048 allowance exists for the hide, which is the whole
    # creature on one unwrap. A lens is 5 cm; at 1024² it already carries more texels
    # per centimetre than the hide does.
    return gmm.write_skin(EYE_MATERIAL, gmm.build_eyes, 0.152,
                          "The lenses: a dying lamp behind fouled glass — dead soot cells, "
                          "a drifting membrane, hot pin flecks. Everything anybody ever sees "
                          "of them is MonsterSkin.EyeGlow multiplied through this map, and "
                          "the map's mean still lands on the calibrated target, so §04's "
                          "관측자 keeps the same pair luminance at ObserverRange while the "
                          "near field stops reading as two cartoon irises.",
                          1024, gmm.pipeline_constants())


def build(variant: dict) -> dict:
    import gen_monster_model as gmm  # noqa: PLC0415

    blendkit.reset_scene()

    src = os.path.join(SOURCE_DIR, variant["source"])
    if not os.path.exists(src):
        blendkit.fail(f"missing base sculpt {src}")

    obj = load_base(src)
    obj.name = variant["asset"] + "_Body"
    raw_tris = triangles(obj)

    # Measured at full resolution, then carried forward. The slab analysis needs a
    # densely sampled mesh: at 5.6k vertices a 200-slab scan sees 28 vertices per
    # slab, and every "is this mass a limb or is it noise" threshold degenerates —
    # measured on the decimated vessel it put the ankle at 0.029 m, which is inside
    # the foot. Decimation barely moves the silhouette, so the reading survives it.
    #
    # Decimation *does* move the extremes by a few millimetres, so the mesh is
    # normalised again afterwards and the landmarks are scaled by the same factor —
    # AssetImportPolicy pins the height to the millimetre.
    normalise(obj)
    # Before measure, because the floating shards are the frontmost thing in the
    # torso band and drag front_y 5 cm off the actual chest.
    strip_debris(obj)
    m = monster_fit.measure(obj)
    decimate(obj, TRI_TARGET)
    normalise(obj)

    # Displacement-only asymmetry (leg bulk, dragged claw, staved temple) — after
    # decimation so it sculpts the vertices that ship, before the rig fit so the
    # eye ray-cast and the skirt anchor against the final surface. Z is untouched,
    # so the landmark heights measured above stay valid.
    gmm.sculpt_asymmetry(obj, m)

    # The head gets its resolution AFTER the asymmetry pass dents it and BEFORE the
    # rig fit, so the eye ray-cast, the maw split and the export all see the dense
    # smoothed skull. The maw channel is torn open inside build_rig, against this
    # refined surface.
    refine_head(obj, m)

    # After refine (the tucked verts must be the dense final ones) and before the
    # rig fit, so the eye ray-cast and the skirt anchor see the reattached shells.
    reattach_head_debris(obj, m)

    # Measured on the bare sculpt, before anything is welded on. This is the density
    # Rodin's own unwrap holds, and it is what the crest and the lenses are then
    # unwrapped to match — taking it afterwards would measure a mesh that includes the
    # very geometry whose UVs are still undecided.
    sculpt_density = gmm.uv_units_per_metre(obj)

    arm_obj, crest_ranges, eye_ranges = build_rig(obj, m, variant["crest"])

    # Everything this file invented gets a planar unwrap at the sculpt's density.
    # Without it the added vertices carry the (0, 0) bmesh leaves behind, and one
    # texel of the atlas is then stretched across the whole crest — a flat patch on
    # the one part of the creature §04's 관측자 is supposed to read a state off.
    project_uvs(obj, crest_ranges + eye_ranges, sculpt_density)

    names = material_names(variant)
    # Follows the variant, so a variant that does not ship cannot leave its hide in
    # Assets/Textures for someone to find later and wonder which creature wears it.
    tex_root = variant["manifest_dir"]
    stats = build_textures(obj, names["hide"], tex_root, m)
    eye_stats = build_eye_textures()

    maw_faces = maw_polygons(obj)
    mats = assign_materials(obj, names, eye_ranges, maw_faces)

    uv_per_metre = float(gmm.uv_units_per_metre(obj))
    hide = hide_entry(names, stats, variant["note"], uv_per_metre)
    materials = [hide, eye_stats, maw_entry(hide)]

    clips = author_clips(arm_obj, obj)

    models = variant["models_dir"]
    textures_dir = variant["manifest_dir"]
    os.makedirs(models, exist_ok=True)
    os.makedirs(textures_dir, exist_ok=True)
    write_manifests(models, textures_dir, variant, clips, materials, uv_per_metre)

    fbx = os.path.join(models, variant["asset"] + ".fbx")
    glb = os.path.join(models, variant["asset"] + ".glb")
    blendkit.export_fbx(fbx, [arm_obj, obj], with_animation=True)

    # Textures go on only now, so the .glb — which docs/ASSETS.md keeps for eyeballing
    # an asset without opening Unity — previews with the graded maps, while the FBX
    # above stays a geometry-and-name handoff.
    hook_textures(mats["hide"], names["hide"], tex_root)
    hook_textures(mats["maw"], names["hide"], tex_root)
    hook_textures(mats["eyes"], names["eyes"], os.path.join(blendkit.UNITY_ASSETS, "Textures"))
    blendkit.export_gltf(glb, with_animation=True)

    return {
        "variant": variant,
        "object": obj,
        "rig": arm_obj,
        "landmarks": m,
        "texture": stats,
        "materials": materials,
        "clips": clips,
        "raw_tris": raw_tris,
        "tris": triangles(obj),
        "fbx": fbx,
        "glb": glb,
    }


def wanted_variants(argv: list[str]) -> list[dict]:
    """The variants this run builds, and where each one is allowed to write.

    Shipping variants go into ``Assets/``; anything else goes to ``artifacts/`` and can
    therefore never be mistaken for the monster the game loads, never be picked up by
    ``AssetImportValidator``, and never quietly become a second answer to "which one is
    it". ``-- --vessel`` opts the human-shaped sculpt back in.
    """
    tail = argv[argv.index("--") + 1:] if "--" in argv else []
    chosen = []
    for variant in VARIANTS:
        if not variant["ships"] and f"--{variant['key']}" not in tail:
            print(f"SKIP {variant['key']:9s} not the shipped monster; "
                  f"pass -- --{variant['key']} to build it into artifacts/")
            continue
        root = blendkit.UNITY_ASSETS if variant["ships"] else os.path.abspath(ARTIFACT_DIR)
        chosen.append({
            **variant,
            "models_dir": (os.path.join(root, "Models", "Characters")
                           if variant["ships"] else root),
            "manifest_dir": os.path.join(root, "Textures") if variant["ships"] else root,
        })
    return chosen


def main() -> None:
    results = []
    for variant in wanted_variants(sys.argv):
        r = build(variant)
        m = r["landmarks"]
        lo, hi = mesh_bounds(r["object"])
        height, width = hi.z - lo.z, hi.x - lo.x
        print(f"FIT {variant['key']:9s} tris={r['raw_tris']}->{r['tris']} "
              f"height={height:.3f} width={width:.3f} "
              f"shoulder={m['shoulder']:.3f} crotch={m['crotch']:.3f} "
              f"knee={m['knee']:.3f} ankle={m['ankle']:.3f} "
              f"elbow={m['elbow']:.3f} wrist={m['wrist']:.3f}")
        for entry in r["materials"]:
            print(f"TEX {entry['name']:20s} albedo={entry['albedo_mean_linear']:.4f} "
                  f"max={entry['albedo_max_linear']:.4f} rough={entry['roughness_mean']:.4f} "
                  f"world={entry['world_size_metres']:.4f}m "
                  f"maps={sorted(k for k, v in entry['maps'].items() if v)}")

        if r["tris"] > TRI_BUDGET:
            blendkit.fail(f"{variant['asset']}: {r['tris']} triangles over the "
                          f"{TRI_BUDGET} budget")
        if width > SHOULDER_LIMIT:
            blendkit.fail(f"{variant['asset']}: {width:.3f} m across — §12 corridors "
                          f"cap it at {SHOULDER_LIMIT} m")
        if abs(height - TARGET_HEIGHT) > 0.002:
            blendkit.fail(f"{variant['asset']}: {height:.4f} m tall, "
                          f"AssetImportPolicy pins {TARGET_HEIGHT}")
        verify_rig(variant, r["rig"])
        verify_clips(variant, r["clips"])
        verify_materials(variant, r["materials"])

        for c in r["clips"]:
            print(f"CLIP {variant['key']:9s} {c['name']:11s} {c['seconds']:6.3f}s "
                  f"loco={str(c['locomotion']):5s} speed={c['ground_speed_mps']:7.4f} "
                  f"slide={c['residual_slide_mps']:7.4f} "
                  f"sink={c['foot_sink_m'] * 1000:+6.2f}mm "
                  f"float={c['foot_float_m'] * 1000:+6.2f}mm")

        results.append(r)
        print(f"ASSET_REPORT {variant['asset']} tris={r['tris']} height={height:.3f} "
              f"clips={len(r['clips'])}")
    return results


# ── Verification ────────────────────────────────────────────────────────────

# The 29 names Unity's code depends on. Not a description of the rig — a contract with
# MonsterRig.cs, MonsterAcquireTell.cs and AssetImportValidator.cs.
REQUIRED_BONES = frozenset(
    ["Hips", "Spine", "Chest", "UpperChest", "Neck", "Head", "Jaw",
     "Crest1", "Crest2", "Crest3", "LeftScapulaSpur"]
    + [f"{side}{part}" for side in ("Left", "Right")
       for part in ("Shoulder", "UpperArm", "LowerArm", "ForearmExtra", "Hand",
                    "UpperLeg", "LowerLeg", "Foot", "Toes")]
)


def verify_rig(variant: dict, arm_obj: bpy.types.Object) -> None:
    have = {b.name for b in arm_obj.data.bones}
    missing = REQUIRED_BONES - have
    if missing:
        blendkit.fail(f"{variant['asset']}: rig is missing {sorted(missing)} — "
                      "AssetImportValidator and MonsterAcquireTell address bones by name")
    extra = have - REQUIRED_BONES
    if extra:
        blendkit.fail(f"{variant['asset']}: rig carries unexpected bones {sorted(extra)}. "
                      "A stray bone is usually the exporter's unweighted-vertex holder, "
                      "which means part of the mesh is not skinned to anything.")


def verify_materials(variant: dict, materials: list[dict]) -> None:
    """Asserts the manifest still says everything ``MonsterSkin`` has to be told.

    Every one of these has a silent failure on the other side of it. A missing
    ``world_size_metres`` makes ``ApplyTiling`` throw and the whole skin build fail — the
    loud case, and the least dangerous. A missing ``Monster_Eyes`` builds a creature with
    no lenses and §04's 관측자 loses the only cue that survives 15 m, with nothing
    logged. A missing ``Monster_Maw`` leaves ``MonsterAcquireTell`` writing an emission
    colour to a material that is not there, every frame of every acquisition, forever.
    """
    by_name = {entry["name"]: entry for entry in materials}
    for required in (variant["material"], EYE_MATERIAL, MAW_MATERIAL):
        if required not in by_name:
            blendkit.fail(f"{variant['asset']}: the skin manifest has no {required} entry")

    for entry in materials:
        if entry.get("world_size_metres", 0.0) <= 0.0:
            blendkit.fail(f"{entry['name']}: world_size_metres is not positive, so "
                          "MonsterSkin.ApplyTiling cannot derive a texture scale")
        for slot in ("albedo", "normal", "roughness", "metallic_smoothness"):
            if not entry["maps"].get(slot):
                blendkit.fail(f"{entry['name']}: no {slot} map. §03 makes the flashlight the "
                              "game's central mechanic and a flat surface gives the beam "
                              "nothing to do — no normal to catch its grazing edge, no "
                              "roughness variation to break its hotspot.")


def verify_clips(variant: dict, clips: list[dict]) -> None:
    by_name = {c["name"]: c for c in clips}
    missing = set(CLIP_ORDER) - set(by_name)
    if missing:
        blendkit.fail(f"{variant['asset']}: clips missing {sorted(missing)}")

    for c in clips:
        # 5 mm, the tolerance gen_monster_model holds itself to. A foot through the
        # floor is the one animation error a dark corridor does not hide.
        if c["foot_sink_m"] < -0.005:
            blendkit.fail(f"{variant['asset']}/{c['name']}: a foot sinks "
                          f"{abs(c['foot_sink_m']) * 1000:.1f} mm through the floor")
        if c["locomotion"] and abs(c["residual_slide_mps"]) > 0.05:
            blendkit.fail(f"{variant['asset']}/{c['name']}: {c['residual_slide_mps']:.3f} "
                          "m/s of foot slide — lock_stance_slide did not converge")

    # §06 calls stillness the game's weapon: the Listener loses the creature when it
    # stops, which is only true if it genuinely stops.
    still = by_name["Standstill"]
    if abs(still["ground_speed_mps"]) > 1e-6:
        blendkit.fail(f"{variant['asset']}: Standstill travels "
                      f"{still['ground_speed_mps']:.4f} m/s — it has to be silent and "
                      "motionless, which is the state's entire purpose")


