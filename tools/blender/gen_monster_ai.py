# The seven §06 states, authored once in gen_monster_model.py and reused verbatim.
# They transfer because they are written as rotations about *world* axes and
# converted per bone through that module's `spec_pose`, so they follow whatever rest
# pose the rig happens to have rather than baking one in — and because every bone
# name here is identical by contract.
CLIP_ORDER = ("Patrol", "Chase", "Alert", "Search", "Standstill", "Stunned", "Grab")


NON_LOOPING = ("Stunned", "Grab")


def author_clips(arm_obj: bpy.types.Object, body: bpy.types.Object) -> list[dict]:
    """Builds the seven clips on the fitted rig, grounds each, and stashes them.

    Grounding is the step that cannot be skipped. Every clip is authored as joint
    rotations against a rest pose, and this rig's rest pose is a sculpt's, not the one
    those rotations were written for — so the same knee angle that planted a foot on
    the original digitigrade skeleton leaves this one hanging in the air or buried in
    the floor. ``gen_monster_model.ground_action`` re-solves the hip height per frame
    against the actual mesh, which is exactly the correction needed and is already
    written, tested and used by the asset that ships today.
    """
    import gen_monster_model as gmm  # noqa: PLC0415 — imported for its clip authors

    builders = {
        "Patrol": gmm.action_patrol,
        "Chase": gmm.action_chase,
        "Alert": gmm.action_alert,
        "Search": gmm.action_search,
        "Standstill": gmm.action_standstill,
        "Stunned": gmm.action_stunned,
        "Grab": gmm.action_grab,
    }

    written = []
    longest = 1
    for name in CLIP_ORDER:
        # The builder's second return value is the gait amplitude, and it is None for
        # exactly the clips that are not locomotion. That is the flag the original
        # generator branches on, so it is the flag used here rather than a hand-kept
        # list of clip names that would drift the first time one is added.
        action, amp = builders[name](arm_obj)
        if action is None:
            blendkit.fail(f"clip {name} produced no action")

        lift = gmm.ground_action(arm_obj, body, action)
        if amp is not None:
            # Locomotion only. Search, Grab and Stunned are *meant* to drift — a
            # creature casting about or recoiling is not holding a stride.
            gmm.lock_stance_slide(arm_obj, action)

        # Measured after both correction passes, because each moves the hips on every
        # frame and therefore moves the foot these numbers are taken from.
        speed, slide = gmm.measure_ground_speed(arm_obj, action)
        # (worst penetration, worst float, hip vertical travel) — sampled on every
        # frame, not just the keys, because the Bézier between two grounded keys can
        # still dip a foot through the floor.
        sink, float_, hip_bob = gmm.grounding_error(arm_obj, body, action)

        frames = int(round(action.frame_range[1] - action.frame_range[0])) + 1
        longest = max(longest, int(math.ceil(action.frame_range[1])))
        written.append({
            "name": name,
            "frames": frames,
            "seconds": round(frames / FPS, 4),
            "loops": name not in NON_LOOPING,
            "locomotion": amp is not None,
            "ground_speed_mps": round(float(speed), 4),
            "residual_slide_mps": round(float(slide), 4),
            "ground_lift_m": round(float(lift), 4),
            "foot_sink_m": round(float(sink), 5),
            "foot_float_m": round(float(float_), 5),
            "hip_bob_m": round(float(hip_bob), 5),
        })
        blendkit.stash_action(arm_obj, action)
    arm_obj.animation_data.action = None

    # The scene range is what the FBX exporter bakes over, so it has to cover the
    # longest clip. Left at a guessed 60 it silently truncates Standstill's 91 frames
    # — and Standstill is the §06 state the design calls the game's weapon.
    blendkit.set_frame_range(1, longest)
    return written


def hide_entry(names: dict, texture: dict, note: str, uv_per_metre: float) -> dict:
    """The sculpt's own surface, described in the shape ``MonsterSkin`` reads.

    One field here is not a measurement of a texture and needs saying out loud.
    ``MonsterSkin.ApplyTiling`` computes ``1 / (uv_units_per_metre × world_size_metres)``
    and puts that on the material as a texture scale, because the rest of the project's
    maps are *tileable patches* drawn at a stated physical size. These are not: Rodin
    baked them to this sculpt's own unwrap, so one tile is the whole creature and the
    only correct scale is exactly 1. Declaring the reciprocal of the measured UV density
    is how that gets said in the vocabulary the manifest already has — and it stays
    correct if the unwrap is ever repacked, because both halves move together.
    """
    hide = names["hide"]
    entry = dict(texture)
    entry.pop("resolution", None)
    return {
        "name": hide,
        "note": note + " Albedo is graded to sit under the darkest §12 corridor wall, so "
                "the creature never announces itself.",
        "world_size_metres": round(1.0 / uv_per_metre, 6),
        **entry,
        "maps": {
            "albedo": f"{hide}/{hide}_albedo.png",
            "normal": f"{hide}/{hide}_normal.png",
            "roughness": f"{hide}/{hide}_rough.png",
            "occlusion": f"{hide}/{hide}_ao.png" if texture.get("ao_mean") else "",
            "metallic_smoothness": f"{hide}/{hide}_ms.png",
        },
    }


def maw_entry(hide: dict) -> dict:
    """The jaw's skin: the hide's own maps, under a second name.

    It is the same surface — it is the same animal — and painting it differently would
    make the mouth read as a separate object stuck to the face. What the second entry
    buys is a second *emission channel*: ``MonsterAcquireTell`` writes
    ``_EmissionColor`` on this slot to light §06's acquisition, and it can only do that
    to a material of its own. Because the emission map is the albedo, the flare then
    takes the shape of the hide's folds rather than flooding a polygon.
    """
    entry = dict(hide)
    entry["maps"] = dict(hide["maps"])   # not the hide's own dict: a shared one would
    entry["name"] = MAW_MATERIAL         # let an edit to either entry move both
    entry["note"] = ("The faces the Jaw bone moves, on the hide's own maps. Split off "
                     "only so §06's acquisition flare has a slot it owns — "
                     "MonsterAcquireTell gapes the mandible and lights this together, "
                     "which is one event and has to look like one.")
    return entry


def write_manifests(models: str, textures: str, variant: dict,
                    clips: list[dict], materials: list[dict], uv_per_metre: float) -> None:
    """Emits the two JSON manifests Unity reads.

    For the shipped variant these land on ``Monster.clips.json`` and
    ``Monster.textures.json`` — the exact paths ``MonsterRig.ClipManifestPath`` and
    ``MonsterSkin.ManifestPath`` hardcode. There is no second copy of either under
    another name, which is the point: a reader who opens either file is looking at the
    creature the game loads.
    """
    with open(os.path.join(models, variant["asset"] + ".clips.json"), "w") as fh:
        json.dump({
            "generated_by": "tools/blender/gen_monster_ai.py",
            "fps": FPS,
            "note": "ground_speed_mps is measured from the weight-bearing foot after "
                    "grounding, not derived. Playback rate for a §07 tier speed is "
                    "tierSpeed / ground_speed_mps.",
            "clips": clips,
        }, fh, indent=2)
        fh.write("\n")

    with open(os.path.join(textures, variant["asset"] + ".textures.json"), "w") as fh:
        json.dump({
            "generated_by": "tools/blender/gen_monster_ai.py",
            "resolution": TEX_RES,
            "uv_units_per_metre": round(uv_per_metre, 6),
            "fbx": f"Assets/Models/Characters/{variant['asset']}.fbx",
            "materials": materials,
        }, fh, indent=2)
        fh.write("\n")


