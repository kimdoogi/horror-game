def _srgb_to_linear(x: np.ndarray) -> np.ndarray:
    return np.where(x <= 0.04045, x / 12.92, ((x + 0.055) / 1.055) ** 2.4)


def _linear_to_srgb(x: np.ndarray) -> np.ndarray:
    x = np.clip(x, 0.0, 1.0)
    return np.where(x <= 0.0031308, x * 12.92, 1.055 * x ** (1.0 / 2.4) - 0.055)


def _resample(img: np.ndarray, res: int) -> np.ndarray:
    """Bilinear resample. Rodin bakes 512²; the monster ships 2048².

    Bilinear and not the nearest-neighbour this used to be: at a 4× upsample nearest
    leaves 4-texel stairs across every baked gradient, and the procedural crack
    relief that now rides on top of these maps traces those stairs faithfully —
    a grid etched into the hide at exactly the range the beam resolves it.
    """
    h, w = img.shape[:2]
    y = np.clip((np.arange(res) + 0.5) * (h / res) - 0.5, 0.0, h - 1.0)
    x = np.clip((np.arange(res) + 0.5) * (w / res) - 0.5, 0.0, w - 1.0)
    y0 = np.floor(y).astype(np.int32)
    x0 = np.floor(x).astype(np.int32)
    y1 = np.minimum(y0 + 1, h - 1)
    x1 = np.minimum(x0 + 1, w - 1)
    fy = (y - y0).astype(np.float32)[:, None, None]
    fx = (x - x0).astype(np.float32)[None, :, None]
    top = img[y0][:, x0] * (1.0 - fx) + img[y0][:, x1] * fx
    bottom = img[y1][:, x0] * (1.0 - fx) + img[y1][:, x1] * fx
    return (top * (1.0 - fy) + bottom * fy).astype(np.float32)


def _image_array(image: bpy.types.Image) -> np.ndarray:
    w, h = image.size
    buf = np.empty(w * h * 4, dtype=np.float32)
    image.pixels.foreach_get(buf)
    return buf.reshape(h, w, 4)


def source_maps(obj: bpy.types.Object) -> dict:
    """Pulls Rodin's baked diffuse / metallic-roughness / normal off the material."""
    out = {}
    for slot in obj.data.materials:
        if slot is None or not slot.use_nodes:
            continue
        for node in slot.node_tree.nodes:
            if node.type != "TEX_IMAGE" or node.image is None:
                continue
            name = node.image.name.lower()
            if "diffuse" in name or "basecolor" in name:
                out["diffuse"] = node.image
            elif "normal" in name:
                out["normal"] = node.image
            elif "rough" in name or "metallic" in name:
                out["orm"] = node.image
    return out


def grade_albedo(diffuse: np.ndarray) -> tuple[np.ndarray, dict]:
    """Puts the sculpt's diffuse on §03's albedo budget: mean 0.17, ceiling 0.2016.

    Measured, not assumed — the creature sculpt arrives at 0.1324 mean linear, i.e.
    already *under* the target, so this is as often a lift as a cut. What the sculpts
    reliably do get wrong is the top end: highlights baked for a turntable sit well
    above the ceiling, and those are what would make the creature announce itself in a
    §12 corridor.

    Above the knee the curve compresses rather than clips, because a clipped highlight
    is a flat white patch and a flat patch on a creature reads as plastic. Compression
    moves the mean down, so the scale is then re-solved against the compressed result
    — a single pass lands at 0.144 and quietly misses the budget it claims to enforce.
    """
    lin = _srgb_to_linear(diffuse[..., :3])
    source_mean = float(lin.mean())
    knee = ALBEDO_MAX * 0.82

    def compress(gain):
        out = lin * gain
        over = out > knee
        out[over] = knee + (ALBEDO_MAX - knee) * np.tanh(
            (out[over] - knee) / (ALBEDO_MAX - knee))
        return out

    gain = ALBEDO_MEAN / max(source_mean, 1e-6)
    graded = compress(gain)
    for _ in range(24):
        err = float(graded.mean())
        if abs(err - ALBEDO_MEAN) <= 1e-4:
            break
        gain *= ALBEDO_MEAN / max(err, 1e-6)
        graded = compress(gain)
    lin = graded

    stats = {
        "albedo_mean_linear": round(float(lin.mean()), 4),
        "albedo_max_linear": round(float(lin.max()), 4),
        "corridor_darkest_linear": CORRIDOR_DARKEST,
        "source_mean_linear": round(source_mean, 4),
        "albedo_gain": round(gain, 4),
    }
    out = diffuse.copy()
    out[..., :3] = _linear_to_srgb(lin)
    return out, stats


def grade_roughness(rough: np.ndarray, target: float, floor: float) -> tuple[np.ndarray, dict]:
    """Puts Rodin's roughness on the mean the hide was calibrated at, keeping its variation.

    Exactly the argument this file already makes one channel over about metallic, applied
    to the channel that decides how §03's beam lands. Rodin lights its sculpts for a
    turntable and returns a fairly glossy surface — measured on the creature, mean 0.436,
    which is *plate* roughness, between the previous asset's carapace (0.380) and the
    inside of its mouth (0.280), and nowhere near its hide (0.836). Under a hard spot a
    metre away that renders as wet plastic; at range it is worse, because a smooth
    surface on a creature twelve pixels wide puts its specular lobe on some pixels and
    not others and crawls frame to frame. ``MonsterBeamResolve`` already fights that by
    rolling smoothness off with distance, and its note says plainly that it can only
    afford to roll it to 0.7 because the highlight is also most of what makes the
    creature visible at 8 m — so the map has to arrive sane rather than be rescued.

    The target is not typed here: it is measured off ``gen_monster_model.build_flesh``,
    which is the hide the corridor pass was calibrated against. Re-paint that surface and
    this follows it.

    Scaled rather than replaced, so the sculpt's own wet patches stay wetter than its dry
    ones — the variation is Rodin's and it is the part worth keeping.
    """
    source_mean = float(rough.mean())
    gain = target / max(source_mean, 1e-6)
    graded = np.clip(rough * gain, floor, 1.0).astype(np.float32)

    # Clipping at the floor moves the mean, so the scale is re-solved against the clipped
    # result — the same two-pass correction grade_albedo needs, for the same reason.
    for _ in range(16):
        err = float(graded.mean())
        if abs(err - target) <= 1e-4:
            break
        gain *= target / max(err, 1e-6)
        graded = np.clip(rough * gain, floor, 1.0).astype(np.float32)

    return graded, {
        "roughness_source_mean": round(source_mean, 4),
        "roughness_gain": round(gain, 4),
    }


def write_png(path: str, data: np.ndarray) -> int:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    h, w = data.shape[:2]
    name = "_w_" + os.path.basename(path)
    img = bpy.data.images.new(name, width=w, height=h, alpha=True)
    img.pixels.foreach_set(np.ascontiguousarray(data, dtype=np.float32).ravel())
    img.file_format = "PNG"
    img.filepath_raw = path
    img.save()
    bpy.data.images.remove(img)
    return os.path.getsize(path)


def hide_roughness() -> float:
    """The roughness the previous asset's hide shipped at, measured rather than copied.

    ``gen_monster_model.build_flesh`` paints it, and every visibility number the shot rig
    has ever reported was measured against a creature whose skin sat there. Reading it
    out of that function costs one 1024² noise field and means a re-paint of the hide
    carries this map with it, instead of leaving the sculpt as the one surface still
    calibrated to a number somebody typed once.
    """
    import gen_monster_model as gmm  # noqa: PLC0415

    return float(gmm.build_flesh(TEX_RES)["roughness"].mean())


def build_textures(obj: bpy.types.Object, material: str, tex_root: str,
                   m: dict) -> dict:
    """Grades and re-emits the sculpt's maps in the layout Unity already expects."""
    import gen_monster_model as gmm  # noqa: PLC0415

    maps = source_maps(obj)
    if "diffuse" not in maps:
        blendkit.fail(f"{material}: the sculpt carries no diffuse map to grade")

    folder = os.path.join(tex_root, material)
    diffuse = _resample(_image_array(maps["diffuse"]), TEX_RES)
    normal = (_resample(_image_array(maps["normal"]), TEX_RES)
              if "normal" in maps else None)
    orm = _resample(_image_array(maps["orm"]), TEX_RES) if "orm" in maps else None

    # Dress the turntable bake into dead flesh BEFORE any grading: cadaveric mottle,
    # cavity-gated craquelure, dry-shell/wet-crevice roughness, real AO. The dressing
    # is shape only — the grades below still own the mean and the corridor ceiling,
    # so §03's albedo policy is enforced on what actually ships. See the docstring on
    # gen_monster_model.dress_sculpt_maps for the shot-review findings this answers.
    #
    # `fields` is the 2026-08 addition: world position, arm-ness and hand-ness
    # rasterised per texel from the skinned mesh, which is what lets the dressing be
    # *anatomical* — craquelure that follows the forearms down to the claws, split
    # skin over the tendons, a dirt gradient toward the hands, and a maw channel
    # that is wet only INSIDE. Runs after build_rig on purpose: the arm masks come
    # from the actual skin weights, not from a guessed bounding box.
    world_size = 1.0 / max(gmm.uv_units_per_metre(obj), 1e-6)
    fields = gmm.rasterize_fields(obj, TEX_RES)
    dressed = gmm.dress_sculpt_maps(diffuse, normal,
                                    orm[..., 1] if orm is not None else None,
                                    TEX_RES, world_size,
                                    fields=fields, landmarks=m)

    graded, stats = grade_albedo(dressed["albedo"])
    stats.update(dressed["stats"])
    written = {"albedo": write_png(os.path.join(folder, f"{material}_albedo.png"), graded)}

    if dressed["normal"] is not None:
        write_png(os.path.join(folder, f"{material}_normal.png"), dressed["normal"])
        written["normal"] = True

    limits = gmm.pipeline_constants()
    rough, rough_stats = grade_roughness(dressed["rough"], hide_roughness(),
                                         limits["MIN_ROUGHNESS"])
    stats.update(rough_stats)

    rgba = np.ones((TEX_RES, TEX_RES, 4), dtype=np.float32)
    rgba[..., 0] = rgba[..., 1] = rgba[..., 2] = rough
    write_png(os.path.join(folder, f"{material}_rough.png"), rgba)

    # Skin is a dielectric. Rodin's metallic channel comes back around 0.45 mean,
    # which under §03's hard spot renders as wet sheet metal — so it is discarded
    # rather than carried through, matching the 0.0 the previous asset shipped.
    # Nothing is written for it: an all-zero map is a texture fetch that returns
    # what the shader's default already is.
    if orm is not None:
        stats["metallic_source_mean"] = round(float(orm[..., 2].mean()), 4)
    stats["metallic_mean"] = 0.0

    # Rodin bakes no occlusion, so this used to be skipped as a constant-white map.
    # The dressing derives a real one from the normal map's own cavities, and it is
    # load-bearing now: §3.14's rim light samples _OcclusionMap, and a rim over
    # creviced skin without AO flattens it back into a paper cut-out.
    rgba = np.ones((TEX_RES, TEX_RES, 4), dtype=np.float32)
    rgba[..., 0] = rgba[..., 1] = rgba[..., 2] = dressed["ao"]
    write_png(os.path.join(folder, f"{material}_ao.png"), rgba)
    stats["ao_mean"] = round(float(dressed["ao"].mean()), 4)

    ms = np.zeros((TEX_RES, TEX_RES, 4), dtype=np.float32)
    ms[..., 3] = 1.0 - rough          # Unity reads smoothness out of alpha
    write_png(os.path.join(folder, f"{material}_ms.png"), ms)

    stats["roughness_mean"] = round(float(rough.mean()), 4)

    stats["resolution"] = TEX_RES
    stats["bytes"] = written["albedo"]
    return stats


def assign_materials(obj: bpy.types.Object, names: dict, eye_ranges: list[tuple],
                     maw_faces: list[int]) -> dict:
    """Replaces the sculpt's imported material with the three the game drives.

    Empty on purpose. Unity imports this FBX with ``materialImportMode: 2`` and no
    external object remapping — exactly as the previous monster does — so the FBX
    carries material *names* and the maps are found under ``Assets/Textures/<name>/``.
    Hooking image nodes up before the FBX export instead makes Blender's exporter copy
    every PNG into a ``.fbx`` sidecar directory, which is a second copy of the same
    textures committed to the repo and a convention this project does not use.

    Three slots and not one, because three separate pieces of Unity code address this
    creature by material name and two of them have nothing to write to on a sculpt:
    ``MonsterBeamResolve`` drives ``_RimStrength`` on every slot, ``MonsterSkin``
    authors the eyes' constant emission on ``Monster_Eyes``, and
    ``MonsterAcquireTell`` fires ``_EmissionColor`` on ``Monster_Maw``. Ownership is by
    material and by property, which is what stops the last two overwriting each other.
    """
    obj.data.materials.clear()
    built = {}
    for key in ("hide", "eyes", "maw"):
        mat = bpy.data.materials.new(names[key])
        mat.use_nodes = True
        obj.data.materials.append(mat)
        built[key] = mat

    slot = {key: i for i, key in enumerate(("hide", "eyes", "maw"))}
    lens = set()
    for start, end, _ in eye_ranges:
        lens.update(range(start, end))

    me = obj.data
    maw = set(maw_faces)
    for poly in me.polygons:
        if all(me.loops[i].vertex_index in lens for i in poly.loop_indices):
            poly.material_index = slot["eyes"]
        elif poly.index in maw:
            poly.material_index = slot["maw"]
        else:
            poly.material_index = slot["hide"]

    counts = {key: sum(1 for p in me.polygons if p.material_index == i)
              for key, i in slot.items()}
    for key in ("eyes", "maw"):
        if counts[key] == 0:
            blendkit.fail(f"{names[key]} ended up on no faces at all. The material would import as "
                          f"an unused slot and the component that drives it would run every frame "
                          f"writing to nothing — which is invisible, and is how this creature "
                          f"shipped with two unlit eyes before.")
    print(f"SLOTS {obj.name} " + " ".join(f"{names[k]}={counts[k]}" for k in slot))
    return built


GLB_PREVIEW_RES = 1024
"""The .glb is an eyeballing preview (docs/ASSETS.md), not what Unity loads — Unity
reads the 2048 PNGs straight from Assets/Textures. Embedding the 2048 set pushed the
preview to 18.9 MB of a git repo for no one; the in-memory copies are halved before
the glTF export re-encodes them, and the PNGs on disk are untouched."""


def hook_textures(mat: bpy.types.Material, material: str, tex_root: str) -> None:
    """Wires the graded maps onto the material, for the .glb preview only."""
    folder = os.path.join(tex_root, material)
    nt = mat.node_tree
    bsdf = next(n for n in nt.nodes if n.type == "BSDF_PRINCIPLED")

    def hook(suffix, socket, non_color):
        path = os.path.join(folder, f"{material}_{suffix}.png")
        if not os.path.exists(path):
            return None
        node = nt.nodes.new("ShaderNodeTexImage")
        node.image = bpy.data.images.load(path, check_existing=True)
        if node.image.size[0] > GLB_PREVIEW_RES:
            node.image.scale(GLB_PREVIEW_RES, GLB_PREVIEW_RES)
            # Pack the scaled buffer, or the glTF exporter ignores the in-memory
            # resize and streams the 2048 file straight off disk — measured: the
            # first cut of this shaved 1.9 MB of 18.9 instead of the ~10 the
            # arithmetic promised, because only the mesh got smaller.
            node.image.pack()
        if non_color:
            node.image.colorspace_settings.name = "Non-Color"
        if socket == "Normal":
            nm = nt.nodes.new("ShaderNodeNormalMap")
            nt.links.new(node.outputs["Color"], nm.inputs["Color"])
            nt.links.new(nm.outputs["Normal"], bsdf.inputs["Normal"])
        else:
            nt.links.new(node.outputs["Color"], bsdf.inputs[socket])
        return node

    hook("albedo", "Base Color", False)
    hook("rough", "Roughness", True)
    hook("normal", "Normal", True)


