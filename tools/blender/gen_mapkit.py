def build_hall() -> list:
    """The 개방 공간: 20 x 20 m, clear 20 m sight lines, 6 m ceiling.

    §12 requires an open space adjacent to maze space and gives it 시야 15~25m,
    because §12's own table shows the Runner must take aggro from **10 m or more**
    for release to be reliable (at 3 m it fails, at 5 m it is "이론상 겨우"). A 20 m
    hall means the Runner can start the chase at double the minimum.

    The four columns sit on grid at 6.25 / 13.75 m, so the centre lines x = 10 and
    y = 10 stay clear for the full 20 m while the columns still give the 섬광수
    somewhere to work. Two openings per wall (also on grid) exist so the hall can be
    part of a 순환로 — §12: "트리 구조는 사형선고."
    """
    s = 8 * GRID  # 20.0 m
    objs: list = []
    c, tp = mat("Ceiling_Structure"), mat("Trim_Painted")
    # One channel down the middle with three gullies: at 20 m across, a hall floor
    # that is dead flat is the largest featureless surface in the game.
    objs += floor_pan("Floor", 0, s, 0, s, mat("Floor_Tile"), depth=FLOOR_T,
                      camber=detail.CAMBER, channel_axis="Y", channel_at=s / 2.0,
                      taper=0.60, cross_divisions=10, run_step=2.5)
    objs += detail.floor_joints("Joint", 0, s, 0, s, run_axis="Y", pitch=2 * GRID)
    for k in range(3):
        objs += floor_drain(f"Drain{k}", s / 2.0, (k + 0.5) * s / 3.0,
                            at_z=-detail.CAMBER)

    half = CLEAR_W / 2.0
    cuts = [(6.25 - half, 6.25 + half, 0.0, CLEAR_H),
            (13.75 - half, 13.75 + half, 0.0, CLEAR_H)]
    for name, x0, x1, y0, y1, room, seed in (
        ("WallS", 0, s, 0, WALL_T, "+Y", 211),
        ("WallN", 0, s, s - WALL_T, s, "-Y", 223),
        ("WallW", 0, WALL_T, WALL_T, s - WALL_T, "+X", 227),
        ("WallE", s - WALL_T, s, WALL_T, s - WALL_T, "-X", 229),
    ):
        objs += dressed_wall(name, x0, x1, y0, y1, room, HALL_H, openings=cuts,
                             pilaster_pitch=2 * GRID, pilaster_phase=1.25,
                             wear_seed=seed)
        wall = wall_of(x0, x1, y0, y1, room)
        for k, (oa0, oa1, _, oz1) in enumerate(cuts):
            objs += opening_frame(f"{name}_case{k}", wall, oa0, oa1, oz1)
        # A string course at gallery level, sitting *on* the door heads — the
        # openings stop at CLEAR_H = 3.00 m, which is exactly GALLERY_RISE, so the
        # course runs continuously without ever crossing a hole. §12 puts the
        # Observer on a 2층 난간 at +3.00 m; carrying that line right round the hall
        # is what makes the height difference readable from the floor, which is the
        # whole point of the post ("없으면 관측자는 죽으러 가야 한다").
        objs.append(_band(wall, f"{name}_string", GALLERY_RISE,
                          GALLERY_RISE + 0.12, tp))

    # Downstand beams spanning between the columns, so the 6 m ceiling has a grid
    # instead of being 400 m² of nothing. §12 wants 시야 15~25 m here — that only
    # helps if there is something up there to judge distance against.
    for a in (6.25, 13.75):
        objs.append(slab(f"HallBeamX{a:.0f}", 0, s, a - 0.22, a + 0.22,
                         HALL_H - 0.55, HALL_H, c, trim=False))
        objs.append(slab(f"HallBeamY{a:.0f}", a - 0.22, a + 0.22, 0, s,
                         HALL_H - 0.55, HALL_H, c, trim=False))
    objs.append(slab("Ceil", 0, s, 0, s, HALL_H, HALL_H + CEIL_T, c, trim=False))
    for k in range(8):
        cpos = (k + 0.5) * s / 8.0
        objs.append(slab(f"HallJoistX{k}", 0, s, cpos - 0.10, cpos + 0.10,
                         HALL_H - 0.26, HALL_H, c))

    for cx in (6.25, 13.75):
        for cy in (6.25, 13.75):
            objs += column(f"Col{cx:.0f}_{cy:.0f}", cx, cy, HALL_H, size=0.50)
    return objs


def _band(wall, name: str, z0: float, z1: float, material,
          depth: float = 0.05) -> bpy.types.Object:
    """A continuous horizontal moulding across a whole wall, openings ignored.

    Only safe **above every opening's head**, because it does no clipping — the one
    caller places it at exactly the openings' head height. A moulding that ran
    across a doorway would be the kind of error that looks deliberate in a
    screenshot and impossible in a building.
    """
    return detail.wall_box(wall, name, wall.a0, wall.a1, 0.0, depth, z0, z1, material)


def build_stairwell() -> list:
    """A metal dog-leg stair climbing one storey (3.75 m). §12 gives stairs 금속.

    §12's Listener table assigns 계단 = 금속 / 울림 — its own material, distinct from
    all four zone surfaces, because a stair is the one place the Listener needs to
    know the monster changed *level*. Treads, landings and the shaft floor are all
    ``Floor_Metal`` and nothing else in the kit uses it as a walking surface.

    **THE LANDING IS THE PIECE — B-001.**

    This stair's spine used to run the full depth of the mid-landing and die into
    the back wall. The two flights therefore never met: they were two disconnected
    surfaces inside one shaft, and nothing — player or monster — could turn round
    between them. ``MapSceneBuilder`` papered over it with a ``NavMeshLink``, which
    is worse than the hole it filled, because ``NavMesh.CalculatePath`` routes
    happily *through* a link and the connectivity audit went green. §06's monster
    does not walk by ``CalculatePath``; it steps along ``NavMeshPath.corners``, a
    link is a gap with nothing to step onto, and it stood at the link mouth for the
    rest of the match without raising a single error.

    So the spine now stops at the head of the flights and continues **below** the
    landing as its support. The mid-landing is one open platform,
    ``STAIR_LANDING_D`` deep across the shaft's full width, and the dog-leg turn is
    geometry. No link is generated for this piece any more, and
    ``MapSceneBuilder.VerifyStairwellsAreWalkable`` fails the build if one ever
    would be again.

    **AND THE TREAD IS THE OTHER HALF.**

    B-001 was about whether the *monster* could turn round on the landing. The same
    piece was, for exactly as long, a stair no *player* could set foot on, and
    nothing measured it: eight treads of 0.30 m going with a 25 mm nosing overhang
    left 0.275 m of usable tread against a capsule that reaches ``PLAYER_TREAD_REACH``
    = 0.30 m forward at the height of the step above. There was no position on any
    tread where the player was not standing inside the next riser, and no position on
    the shaft floor where they were not standing inside the first one. The NavMesh
    did not care — Recast erodes a region, it does not carry a body — so the audit
    read 1830/1830 with one island while four of the building's five storeys were
    sealed. See ``PlayerTraversal`` in the Unity project, which is the check that
    would have caught it.

    Everything that decides whether it bakes is derived rather than chosen — see
    the ``STAIR_*`` constants and the 계단 rows in ``design_checks``. In summary:
    6 treads per flight at 0.3125 m rise x 0.38 m going, 2.20 m clear stair width
    less a 0.06 m handrail, 2.05 m of landing, 0.08 m of capsule clearance on every
    tread, 3.00 m of headroom at the tightest point of the climb.

    The spine still separates the flights along their whole run, so the stairwell
    remains a 연속 차단 structure and not merely vertical circulation — what changed
    is that the break now ends where a real dog-leg's does, at the landing. The
    void under the upper flight is 1.73 m high: below the agent's 2.00 m, so the
    bake correctly refuses to send the monster in there, and §12's checklist wants
    은폐 지점.
    """
    s = 2 * GRID  # 5.0 m square shaft
    steps = STAIR_STEPS
    rise = STAIR_RISE                     # 0.234375 m
    going = STAIR_GOING
    run = STAIR_RUN                       # 2.40 m
    half = STOREY / 2.0                   # mid-landing top, 1.875 m
    y_foot = STAIR_APPROACH
    y_head = y_foot + run                 # 0.40 -> 2.80
    top_h = STOREY + CLEAR_H              # wall height, 6.75 m

    objs: list = []
    w, c, fm = mat("Wall_Structure"), mat("Ceiling_Structure"), mat("Floor_Metal")
    st, tp = mat("Trim_Steel"), mat("Trim_Painted")
    objs.append(slab("Floor", 0, s, 0, s, -FLOOR_T, 0.0, fm, floor=True))
    objs.append(slab("Ceil", 0, s, 0, s, top_h, top_h + CEIL_T, c, trim=False))

    ax0, ax1 = WALL_T, WALL_T + CLEAR_W           # 0.15 .. 2.35
    bx0, bx1 = s - WALL_T - CLEAR_W, s - WALL_T   # 2.65 .. 4.85

    for k in range(steps):  # flight A: ascends +Y from 0 to 1.875 m
        objs.append(slab(f"A_Step{k}", ax0, ax1, y_foot + k * going,
                         y_foot + (k + 1) * going, 0.0, (k + 1) * rise, fm, floor=True))
        # Nosing: the band that marks each tread's edge. On a metal stair it is
        # the only thing that separates one tread from the next in a beam, and §12
        # gives 계단 its own Listener row precisely because players must *know*
        # they are on stairs. It sits on the tread and does NOT overhang the riser
        # below — see STAIR_NOSE_W. An overhang lies at exactly the height a
        # climbing capsule is widest and is subtracted, millimetre for millimetre,
        # from the only clearance a player has.
        objs.append(slab(f"A_Nose{k}", ax0, ax1, y_foot + k * going,
                         y_foot + k * going + STAIR_NOSE_W, (k + 1) * rise - 0.035,
                         (k + 1) * rise, st, floor=True))
    # The mid-landing: full width of the shaft, STAIR_LANDING_D deep, and nothing
    # standing on it. Flush with the head of flight A and one riser below the foot
    # of flight B, so all three are a single connected surface to the bake.
    objs.append(slab("MidLanding", ax0, bx1, y_head, s - WALL_T,
                     half - FLOOR_T, half, fm, floor=True))
    for k in range(steps):  # flight B: ascends -Y from 1.875 to 3.75 m
        objs.append(slab(f"B_Step{k}", bx0, bx1, y_head - (k + 1) * going,
                         y_head - k * going, half - FLOOR_T,
                         half + (k + 1) * rise, fm, floor=True))
        objs.append(slab(f"B_Nose{k}", bx0, bx1, y_head - k * going - STAIR_NOSE_W,
                         y_head - k * going,
                         half + (k + 1) * rise - 0.035,
                         half + (k + 1) * rise, st, floor=True))
    objs.append(slab("TopLanding", bx0, bx1, WALL_T, y_foot,
                     STOREY - FLOOR_T, STOREY, fm, floor=True))

    # Spine wall: steps up with flight A, so neither flight can see the other. It
    # stops at y_head — the head of the flights — and *not* at the back wall, which
    # is the whole of B-001. Below the landing it continues as SpineUnder, so the
    # slab is still carried on a wall rather than cantilevered off two edges.
    for k in range(steps):
        objs.append(slab(f"Spine{k}", ax1, bx0, y_foot + k * going,
                         y_foot + (k + 1) * going, 0.0, (k + 1) * rise + 1.05, w,
                         trim=False))
        # Raking handrail on the spine, following flight A.
        objs.append(slab(f"Rail{k}", ax1 - STAIR_RAIL_D, ax1, y_foot + k * going,
                         y_foot + (k + 1) * going, (k + 1) * rise + 0.94,
                         (k + 1) * rise + 1.05, st))
        # Flight B's handrail goes on the shaft wall instead of the spine: the
        # spine only rises with flight A, so a rail hung off it at flight B's
        # height would float. Same projection either side, which is what lets
        # design_checks quote one clear stair width for the pair.
        objs.append(slab(f"BRail{k}", bx1 - STAIR_RAIL_D, bx1,
                         y_head - (k + 1) * going, y_head - k * going,
                         half + (k + 1) * rise + 0.94,
                         half + (k + 1) * rise + 1.05, st))
    # Support under the landing, stopping at its soffit. Everything above the
    # walking surface is gone: a wall here, or a coping, or anything else within
    # NAV_AGENT_HEIGHT of the landing, closes the turn again.
    objs.append(slab("SpineUnder", ax1, bx0, y_head, s - WALL_T, 0.0,
                     half - FLOOR_T, w, trim=False))
    objs.append(slab("SpineCap", ax1 - 0.05, bx0 + 0.05, y_foot, y_head,
                     half + 1.05, half + 1.14, tp))
    # Newel: the spine's exposed end, thickened and run up past the coping so the
    # turn has something to read as a corner. Kept inside the spine's own footprint
    # in Y — a post that projected onto the landing would come straight off
    # STAIR_LANDING_D.
    objs.append(slab("Newel", ax1 - 0.04, bx0 + 0.04, y_head - 0.14, y_head,
                     0.0, half + 1.30, tp))

    # Perimeter. The -Y wall carries both the lower entry and the upper exit, which
    # is what makes this piece the join between two storeys of the grid.
    objs += dressed_wall("WallS", 0, s, 0, WALL_T, "+Y", top_h, openings=[
        (ax0, ax1, 0.0, CLEAR_H),
        (bx0, bx1, STOREY, top_h),
    ], pilaster_pitch=0.0, wear_seed=307)
    # No pilaster on the back wall, unlike every other closing wall in the kit.
    # This is the one wall an agent's turning circle is measured against — it is
    # the far side of the landing — and a 0.06 m pilaster comes off STAIR_LANDING_D
    # for the whole height of the shaft.
    objs += dressed_wall("WallN", 0, s, s - WALL_T, s, "-Y", top_h,
                         pilaster_pitch=0.0, wear_seed=311)
    objs += dressed_wall("WallW", 0, WALL_T, WALL_T, s - WALL_T, "+X", top_h,
                         pilaster_pitch=2 * GRID, pilaster_phase=1.25, wear_seed=313)
    objs += dressed_wall("WallE", s - WALL_T, s, WALL_T, s - WALL_T, "-X", top_h,
                         pilaster_pitch=2 * GRID, pilaster_phase=1.25, wear_seed=317)
    objs += opening_frame("EntryCase", wall_of(0, s, 0, WALL_T, "+Y"),
                          ax0, ax1, CLEAR_H - 0.6)

    # A riser of pipework climbing out of the mid-landing. A stairwell is a
    # vertical service route in every real building, and the vertical run is what
    # tells the player this shaft goes somewhere above the one storey they can
    # walk — which is exactly the impression §12 wants from 계단, the only piece
    # that changes the Listener's answer from a zone to a level.
    rx, ry = 0.34, s - 0.34
    objs.append(pipe("Riser", "Z", STOREY / 2, top_h, rx, ry, 0.065, st))
    objs.append(pipe("RiserB", "Z", STOREY / 2, top_h, rx + 0.19, ry, 0.032, st, sides=6))
    for k in range(3):
        z = STOREY / 2 + 0.55 + k * 1.45
        objs.append(pipe(f"RiserCollar{k}", "Z", z, z + 0.09, rx, ry, 0.088, st))
        objs.append(slab(f"RiserClip{k}", rx - 0.10, rx + 0.26, ry, ry + 0.30,
                         z + 0.02, z + 0.06, st, raw=True))
    return objs


def build_gallery() -> list:
    """A 15 m raised walkway with a barred parapet — §04's Observer post.

    §04: the Observer reads the monster's vision from **within 15 m**, holding still
    3 s. §12: "높이 차(2층 난간) · 창문 · 격자 등 15m 거리에서 안전하게 괴물을 볼 수 있는
    지점을 구역당 1~2개 배치. 없으면 관측자는 죽으러 가야 한다."

    So 15 m is the piece's length, not a coincidence: an Observer standing at one end
    covers the whole deck at exactly the ability's range. Placed at
    ``GALLERY_RISE`` = 3.00 m above the floor it overlooks, a monster at 14.70 m
    horizontally is at a slant range of exactly 15.00 m — inside the 20 m hall, so
    the geometry actually delivers the number.

    Safety is structural: a 0.35 m kerb, 0.75 m of steel bars at 0.75 m centres and a
    top rail at 1.05-1.20 m. The deck is ``Floor_Concrete`` rather than metal on
    purpose — §12 reserves 금속 for stairs, and a ringing catwalk would put a false
    stairwell into the Listener's map.
    """
    length = 6 * GRID  # 15.0 m
    objs: list = []
    w, c, st = mat("Wall_Structure"), mat("Ceiling_Structure"), mat("Trim_Steel")
    tp = mat("Trim_Painted")
    objs.append(slab("Deck", 0, GRID, 0, length, -FLOOR_T, 0.0,
                     mat("Floor_Concrete"), floor=True))
    objs += framed_ceiling("Ceil", 0, GRID, 0, length, CLEAR_H, span="X", slab_t=CEIL_T)
    objs += dressed_wall("BackWall", 0, WALL_T, 0, length, "+X", CLEAR_H,
                         pilaster_pitch=GRID, pilaster_phase=GRID / 2, wear_seed=401)

    # The parapet, built as a real one: kerb, panel, coping, standards, top rail.
    # An Observer holds still for 3 s at 15 m (§04) — they are looking *over* this
    # edge for that whole time, so it is the geometry they stare at longest in the
    # match, and it was a single 0.35 m box.
    objs.append(slab("Kerb", GRID - WALL_T, GRID, 0, length, 0.0, 0.35, w, trim=False))
    objs.append(slab("KerbCap", GRID - WALL_T - 0.045, GRID, 0, length,
                     0.35, 0.40, tp))
    objs.append(slab("TopRail", GRID - WALL_T - 0.03, GRID, 0, length, 1.05, 1.20, st))
    objs.append(slab("MidRail", GRID - 0.115, GRID - 0.075, 0, length, 0.72, 0.78, st))
    n_bars = int(round(length / 0.75))
    for k in range(n_bars):
        yc = (k + 0.5) * (length / n_bars)
        objs.append(slab(f"Bar{k}", GRID - 0.125, GRID - 0.070,
                         yc - 0.025, yc + 0.025, 0.40, 1.10, st))
    for k in range(int(length / 2.5) + 1):
        yc = min(length - 0.06, k * 2.5 + 0.06)
        objs.append(slab(f"Standard{k}", GRID - WALL_T, GRID, yc - 0.055, yc + 0.055,
                         0.35, 1.20, st))
    # Both ends stay open — §12 wants every worthwhile spot to have two escape
    # routes. Only a header beam closes them off overhead.
    objs.append(slab("HeadS", WALL_T, GRID - WALL_T, 0, WALL_T, DOOR_H, CLEAR_H, w,
                     trim=False))
    objs.append(slab("HeadN", WALL_T, GRID - WALL_T, length - WALL_T, length,
                     DOOR_H, CLEAR_H, w, trim=False))

    # No soffit brackets, deliberately. A cantilevered deck wants visible corbels
    # underneath, but the kit's contract is that every piece's lowest point is
    # exactly −FLOOR_T so the grid assembler can place it blind (verify_piece
    # asserts it). Anything hanging below the deck would break that for one piece
    # and quietly invalidate the assumption for all of them, so the support reads
    # through the parapet and the deck edge instead.
    objs += cable_tray("Tray", "Y", 0.0, length, WALL_T + detail.TRAY_LANE,
                       wall_face=WALL_T)
    objs += junction_box("JBox", wall_of(0, WALL_T, 0, length, "+X"), 7.5, 1.55)
    return objs


