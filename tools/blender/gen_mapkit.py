def build_doorway_frame() -> list:
    """A 2.5 m cell with a 2.20 x 2.40 m framed opening across it.

    §12 puts 잠글 수 있는 문 1~2개 per zone at bottlenecks, and singles out the neck
    of a 순환로: "잠그면 순환이 끊김 (전략적 선택)". The opening is the full 2.20 m
    corridor width because §03's objective has to come *out* through it and §08 makes
    the w5 궤짝 a two-person carry — a 1.2 m single door would silently make the
    objective uncarryable.

    The hardware is hung on the partition *face*, not inside the opening, so the
    2.20 m structural opening loses nothing to pintles — only 30 mm per side to the
    jamb lining, leaving 2.14 m. The 2.20 m of leaves (2 × 1.10 m) therefore still
    fills the opening and laps the lining, which is how a face-hung bulkhead door
    is actually built and the only version where §12's stated opening and §08's
    carry are both true. ``design_checks()`` recomputes both numbers each run.
    """
    objs: list = []
    w, st = mat("Wall_Structure"), mat("Trim_Steel")
    corridor_floor(objs, 0, GRID, 0, GRID, mat("Floor_Concrete"), drain_every=99.0)
    objs += framed_ceiling("Ceil", 0, GRID, 0, GRID, CLEAR_H, span="X", slab_t=CEIL_T)
    # No pilasters on the side walls here: the door piers below do that job, and
    # two rhythms 0.15 m apart would fight rather than read.
    objs += dressed_wall("WallW", 0, WALL_T, 0, GRID, "+X", CLEAR_H,
                         pilaster_pitch=0.0, wear_seed=601)
    objs += dressed_wall("WallE", GRID - WALL_T, GRID, 0, GRID, "-X", CLEAR_H,
                         pilaster_pitch=0.0, wear_seed=607)

    cy0, cy1 = GRID / 2 - WALL_T / 2, GRID / 2 + WALL_T / 2   # 1.175 .. 1.325
    objs.append(slab("Lintel", WALL_T, GRID - WALL_T, cy0, cy1, DOOR_H, CLEAR_H, w,
                     trim=False))
    # Piers: the partition thickens against each side wall so the opening is a hole
    # in a wall rather than a lintel floating between two corridor surfaces. They
    # project along the corridor, not into it, so the 2.20 m opening is untouched.
    for tag, px0, px1 in (("W", 0.0, WALL_T), ("E", GRID - WALL_T, GRID)):
        objs.append(slab(f"Pier{tag}", px0, px1, cy0 - 0.14, cy1 + 0.14, 0.0, CLEAR_H,
                         w, trim=False))
        objs.append(slab(f"PierCap{tag}", px0, px1, cy0 - 0.19, cy1 + 0.19,
                         DOOR_H + 0.10, DOOR_H + 0.28, mat("Trim_Painted")))

    # The frame proper: jamb linings, a head lining, a stop bead and architraves on
    # both faces. §12 puts a lockable door at the neck of a 순환로 and calls locking
    # it a 전략적 선택 — a decision the team has to *see* coming, down a dark corridor,
    # which a bare hole in a wall does not communicate at any distance.
    #
    # The structural opening stays the full 2.20 m corridor width so two 1.10 m
    # leaves still fill it; see door_lining on why face-hung leaves make that work.
    # No side architraves: the opening is the full corridor width, so the side
    # walls *are* the jambs and a vertical casing would be buried inside them. The
    # reveal lining plus the piers frame the opening instead.
    objs += door_lining("Frame", WALL_T, GRID - WALL_T, cy0, cy1, DOOR_H,
                        side_architraves=False)
    # Head casing sits on the wall faces above the opening, so it costs no width.
    objs.append(slab("HeadCaseA", WALL_T, GRID - WALL_T, cy0 - 0.14, cy0 - 0.09,
                     DOOR_H + 0.12, DOOR_H + 0.24, st))
    objs.append(slab("HeadCaseB", WALL_T, GRID - WALL_T, cy1 + 0.09, cy1 + 0.14,
                     DOOR_H + 0.12, DOOR_H + 0.24, st))
    # Pintles hang on the partition *face*, clear of the opening, so the hardware
    # costs no passing width at all — the kit's old 2.08 m pinch was here.
    for k, z in enumerate((0.20, 1.10, 2.15)):
        objs.append(slab(f"PintleW{k}", WALL_T, WALL_T + 0.075, cy1 + 0.028, cy1 + 0.115,
                         z, z + 0.14, st))
        objs.append(slab(f"PintleE{k}", GRID - WALL_T - 0.075, GRID - WALL_T,
                         cy1 + 0.028, cy1 + 0.115, z, z + 0.14, st))
    # Strike keep at the meeting stile: what the Engineer's lock actually engages.
    objs.append(slab("StrikeKeep", GRID / 2 - 0.05, GRID / 2 + 0.05, cy1 + 0.012,
                     cy1 + 0.085, 1.02, 1.32, st))
    return objs


