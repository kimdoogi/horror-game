def build_junction_cross() -> list:
    """A 4-way. Two of these in a zone make a loop unavoidable (§12)."""
    objs: list = []
    w, c = mat("Wall_Structure"), mat("Ceiling_Structure")
    objs.append(slab("Floor", 0, GRID, 0, GRID, -FLOOR_T, 0.0,
                     mat("Floor_Concrete"), floor=True))
    objs.append(slab("Ceil", 0, GRID, 0, GRID, CLEAR_H, CLEAR_H + CEIL_T, c))
    for nx, ny, tag in ((0, 0, "SW"), (1, 0, "SE"), (0, 1, "NW"), (1, 1, "NE")):
        x0 = 0.0 if nx == 0 else GRID - WALL_T
        y0 = 0.0 if ny == 0 else GRID - WALL_T
        objs.append(slab(f"Post{tag}", x0, x0 + WALL_T, y0, y0 + WALL_T,
                         0.0, CLEAR_H, w))
    # Cross beams: the 4-way has no walls at all, so the ceiling needs carrying and
    # the junction needs something for a flashlight to catch (§05).
    objs.append(slab("BeamX", 0, GRID, GRID / 2 - 0.09, GRID / 2 + 0.09,
                     CLEAR_H - 0.26, CLEAR_H, w))
    objs.append(slab("BeamY", GRID / 2 - 0.09, GRID / 2 + 0.09, 0, GRID,
                     CLEAR_H - 0.26, CLEAR_H, w))
    return objs


def build_dead_end() -> list:
    """A 2.5 x 5 m dead end whose reward is part of the geometry.

    §12 wants 막힌 길 비율 20~25% and pairs it with 막힌 길 보상 = 전리품 · 자재,
    reason: "위험을 감수할 이유". A cap with no reward is the failure mode this piece
    exists to make impossible — the loot plinth and the alcove ship with it.
    """
    depth = 2 * GRID
    objs: list = []
    w, c, st = mat("Wall_Structure"), mat("Ceiling_Structure"), mat("Trim_Steel")
    objs.append(slab("Floor", 0, GRID, 0, depth, -FLOOR_T, 0.0,
                     mat("Floor_Concrete"), floor=True))
    objs.append(slab("Ceil", 0, GRID, 0, depth, CLEAR_H, CLEAR_H + CEIL_T, c))
    objs.append(slab("WallW", 0, WALL_T, 0, depth, 0.0, CLEAR_H, w))
    objs.append(slab("WallE", GRID - WALL_T, GRID, 0, depth, 0.0, CLEAR_H, w))

    # North wall, built around a 1.25 x 0.22 x 1.35 m alcove over a 0.55 m shelf.
    ny0, ny1 = depth - 0.30, depth
    objs.append(slab("N_L", WALL_T, 0.70, ny0, ny1, 0.0, CLEAR_H, w))
    objs.append(slab("N_R", 1.95, GRID - WALL_T, ny0, ny1, 0.0, CLEAR_H, w))
    objs.append(slab("N_Back", 0.70, 1.95, ny1 - 0.08, ny1, 0.0, CLEAR_H, w))
    objs.append(slab("N_Head", 0.70, 1.95, ny0, ny1 - 0.08, 1.90, CLEAR_H, w))
    objs.append(slab("N_Shelf", 0.70, 1.95, ny0, ny1 - 0.08, 0.0, 0.55, w))
    # The plinth: where the 전리품 sits. Steel, so it reads as salvage staging.
    objs.append(slab("Plinth", 0.90, 1.75, depth - 1.05, depth - 0.50, 0.0, 0.60, st))
    objs.append(slab("PlinthTop", 0.84, 1.81, depth - 1.11, depth - 0.44,
                     0.60, 0.66, st))
    corbels(objs, "Y", depth, w, WALL_T, GRID - WALL_T)
    return objs


