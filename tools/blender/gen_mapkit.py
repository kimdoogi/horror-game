# ── Corridor services, shared by every corridor-section piece ───────────────


def corridor_services(objs: list, axis: str, a0: float, a1: float,
                      west_face: float, east_face: float,
                      ceiling: float = CLEAR_H) -> None:
    """Pipe run, cable tray and conduit threaded along one corridor section.

    The lane offsets come from ``gen_mapkit_detail`` and are the same in every
    piece, which is the entire point: a service run that stops at a dock is what
    exposes a level as a kit. Threaded through, it is the strongest single cue
    that the corridors are one building — and §03 makes it narratively load-
    bearing too, because §04's Engineer restores light from a panel and the cable
    is the visible half of that system.

    ``west_face`` / ``east_face`` are the finished faces of the two walls on the
    cross axis, so this works for a corridor running along either axis.
    """
    st = mat("Trim_Steel")
    pipe_at = west_face + detail.PIPE_LANE
    tray_at = east_face - detail.TRAY_LANE

    objs += pipe_run("Pipe", axis, a0, a1, pipe_at)
    # A second, smaller pipe beside the first. Two parallel runs at different radii
    # read as a services corridor; one reads as a design element.
    objs.append(pipe("PipeSmall", axis, a0, a1, west_face + 0.62,
                     detail.PIPE_Z + 0.11, 0.035, st, sides=6))
    objs += cable_tray("Tray", axis, a0, a1, tray_at, wall_face=east_face)


def corridor_floor(objs: list, x0: float, x1: float, y0: float, y1: float,
                   material: bpy.types.Object, channel_axis: str = "Y",
                   drain_every: float = 5.0) -> None:
    """A cambered slab plus a drain every ``drain_every`` metres of run.

    §12's building is a basement, so the floor falls to a channel. The camber
    tapers to flat at the piece ends, which is what keeps §12's grid promise that
    pieces simply abut — see ``floor_pan``.
    """
    channel_at = (x0 + x1) / 2.0 if channel_axis == "Y" else (y0 + y1) / 2.0
    objs += floor_pan("Floor", x0, x1, y0, y1, material, depth=FLOOR_T,
                      channel_axis=channel_axis, channel_at=channel_at)
    objs += detail.floor_joints("Joint", x0, x1, y0, y1, run_axis=channel_axis,
                                pitch=GRID)

    run_lo, run_hi = (y0, y1) if channel_axis == "Y" else (x0, x1)
    n = int((run_hi - run_lo) // drain_every)
    for k in range(n):
        a = run_lo + (k + 0.5) * (run_hi - run_lo) / n
        cx, cy = (channel_at, a) if channel_axis == "Y" else (a, channel_at)
        objs += floor_drain(f"Drain{k}", cx, cy, at_z=-detail.CAMBER)


# ── Corridors ───────────────────────────────────────────────────────────────


def build_straight(length: float) -> Callable[[], list]:
    """A straight corridor of `length` m — the kit's reference cross-section.

    §12 caps 직선 통로 at 20 m ("넘으면 주자가 죽는다"), so the kit's longest straight
    is 10 m — half the ceiling. Two 10 m pieces butted end to end reach exactly the
    limit and nothing in the kit can exceed it.

    Everything about the *elevation* is decided here and reused by the other
    corridor pieces, because §05's flashlight is the only light and a corridor has
    to stay legible as it turns. Bottom to top: cambered slab falling to a central
    channel with a gully every 5 m; skirting; damp band to 1.02 m; dado rail at
    chest height where the beam rakes; pilasters on the 2.5 m grid; cornice; joists
    at a fixed 1.25 m pitch overhead; a pipe run down one side and a cable tray
    down the other. None of it narrows the corridor below 2.08 m, which is still
    2.8 × the monster's shoulders and above §08's two-person 궤짝 carry.
    """
    def build() -> list:
        objs: list = []
        corridor_floor(objs, 0, GRID, 0, length, mat("Floor_Concrete"))
        objs += framed_ceiling("Ceil", 0, GRID, 0, length, CLEAR_H, span="X",
                               slab_t=CEIL_T)
        objs += dressed_wall("WallW", 0, WALL_T, 0, length, "+X", CLEAR_H,
                             pilaster_pitch=GRID, pilaster_phase=GRID / 2,
                             wear_seed=int(length * 100) + 11)
        objs += dressed_wall("WallE", GRID - WALL_T, GRID, 0, length, "-X", CLEAR_H,
                             pilaster_pitch=GRID, pilaster_phase=GRID / 2,
                             wear_seed=int(length * 100) + 23)
        corridor_services(objs, "Y", 0.0, length, WALL_T, GRID - WALL_T)

        west = wall_of(0, WALL_T, 0, length, "+X")
        east = wall_of(GRID - WALL_T, GRID, 0, length, "-X")
        # One vent and one junction box per 5 m, staggered across the corridor so a
        # player sweeping the beam finds something on either side rather than a
        # repeating strip on one.
        for k in range(max(1, int(length // (2 * GRID)))):
            base = (k + 0.5) * length / max(1, int(length // (2 * GRID)))
            objs += wall_vent(f"VentW{k}", west, base - 0.9, 2.10)
            objs += junction_box(f"JBoxE{k}", east, base + 0.9, 1.55)
        objs += conduit_along("ConduitE", east, 0.0, length, count=2)
        return objs
    return build


def build_corner_l() -> list:
    """A 90° turn in one 2.5 m cell, open on -Y and +X.

    Four of these plus the straights rebuild §12's S-corridor by hand:
    corner + 5 m + 2.5 m = a 10 m leg, exactly.

    The corner is where the §05 detail budget is best spent, because it is the one
    place a Runner at 5.6 m/s has to judge geometry rather than follow it. So the
    inner corner gets a real quoined post with a chamfered nosing, the services
    turn the corner instead of stopping at it, and the ceiling frame changes
    direction with a header beam over the junction.
    """
    objs: list = []
    w, tp, st = mat("Wall_Structure"), mat("Trim_Painted"), mat("Trim_Steel")
    corridor_floor(objs, 0, GRID, 0, GRID, mat("Floor_Concrete"), drain_every=99.0)
    objs += framed_ceiling("Ceil", 0, GRID, 0, GRID, CLEAR_H, span="X",
                           slab_t=CEIL_T, joist_pitch=1.25)
    objs += dressed_wall("WallW", 0, WALL_T, 0, GRID, "+X", CLEAR_H,
                         pilaster_pitch=GRID, pilaster_phase=GRID / 2, wear_seed=41)
    objs += dressed_wall("WallN", WALL_T, GRID, GRID - WALL_T, GRID, "-Y", CLEAR_H,
                         pilaster_pitch=0.0, wear_seed=47)

    # The inner corner post carries the ceiling and gives the turn a hard edge to
    # read against. Quoins — alternating projecting blocks — cost six boxes and
    # turn a bare arris into the single most legible vertical in the piece.
    objs.append(slab("PostSE", GRID - WALL_T, GRID, 0, WALL_T, 0.0, CLEAR_H, w,
                     trim=False))
    for k in range(6):
        z0 = 0.10 + k * 0.42
        objs.append(slab(f"Quoin{k}", GRID - WALL_T - 0.055, GRID,
                         0, WALL_T + 0.055, z0, z0 + 0.24, tp))
    objs.append(slab("PostCap", GRID - WALL_T - 0.07, GRID, 0, WALL_T + 0.07,
                     2.62, 2.80, tp))

    # Header beam across the mouth of the turn: the ceiling frame has to change
    # direction somewhere and the change is worth showing.
    objs.append(slab("Header", WALL_T, GRID, GRID - WALL_T - 0.22, GRID - WALL_T,
                     CLEAR_H - 0.24, CLEAR_H, mat("Ceiling_Structure"), trim=False))

    # Services turn the corner. A pipe that stops at a corner is worse than no
    # pipe at all — it says the building ends here.
    pipe_at = WALL_T + detail.PIPE_LANE
    objs.append(pipe("PipeIn", "Y", 0.0, pipe_at, pipe_at, detail.PIPE_Z, detail.PIPE_R, st))
    objs.append(pipe("PipeOut", "X", pipe_at, GRID, pipe_at, detail.PIPE_Z, detail.PIPE_R, st))
    objs.append(slab("PipeElbow", pipe_at - 0.10, pipe_at + 0.10,
                     pipe_at - 0.10, pipe_at + 0.10,
                     detail.PIPE_Z - 0.095, detail.PIPE_Z + 0.095, st))
    tray_at = GRID - WALL_T - detail.TRAY_LANE
    objs += cable_tray("TrayIn", "Y", 0.0, tray_at, tray_at, wall_face=GRID - WALL_T)
    objs += cable_tray("TrayOut", "X", tray_at, GRID, tray_at, wall_face=GRID - WALL_T)
