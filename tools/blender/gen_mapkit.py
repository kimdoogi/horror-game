def build_stairwell() -> list:
    """A metal dog-leg stair climbing one storey (3.75 m). §12 gives stairs 금속.

    §12's Listener table assigns 계단 = 금속 / 울림 — its own material, distinct from
    all four zone surfaces, because a stair is the one place the Listener needs to
    know the monster changed *level*. Treads, landings and the shaft floor are all
    ``Floor_Metal`` and nothing else in the kit uses it as a walking surface.

    9 treads per flight, 0.2083 m rise x 0.30 m going, 2.20 m clear stair width.
    The spine wall between the flights breaks line of sight between them, so the
    stairwell is also a 연속 차단 structure and not just vertical circulation. The
    void under the upper flight is 1.73 m high — §12's checklist wants 은폐 지점.
    """
    s = 2 * GRID  # 5.0 m square shaft
    flights, steps = 2, 9
    rise = STOREY / (flights * steps)     # 0.208333 m
    going = 0.30
    run = steps * going                   # 2.70 m
    y_foot, y_head = 0.40, 0.40 + run     # 0.40 -> 3.10
    top_h = STOREY + CLEAR_H              # wall height, 6.75 m

    objs: list = []
    w, c, fm = mat("Wall_Structure"), mat("Ceiling_Structure"), mat("Floor_Metal")
    objs.append(slab("Floor", 0, s, 0, s, -FLOOR_T, 0.0, fm, floor=True))
    objs.append(slab("Ceil", 0, s, 0, s, top_h, top_h + CEIL_T, c))

    ax0, ax1 = WALL_T, WALL_T + CLEAR_W           # 0.15 .. 2.35
    bx0, bx1 = s - WALL_T - CLEAR_W, s - WALL_T   # 2.65 .. 4.85

    for k in range(steps):  # flight A: ascends +Y from 0 to 1.875 m
        objs.append(slab(f"A_Step{k}", ax0, ax1, y_foot + k * going,
                         y_foot + (k + 1) * going, 0.0, (k + 1) * rise, fm, floor=True))
    objs.append(slab("MidLanding", ax0, bx1, y_head, s - WALL_T,
                     STOREY / 2 - FLOOR_T, STOREY / 2, fm, floor=True))
    for k in range(steps):  # flight B: ascends -Y from 1.875 to 3.75 m
        objs.append(slab(f"B_Step{k}", bx0, bx1, y_head - (k + 1) * going,
                         y_head - k * going, STOREY / 2 - FLOOR_T,
                         STOREY / 2 + (k + 1) * rise, fm, floor=True))
    objs.append(slab("TopLanding", bx0, bx1, WALL_T, y_foot,
                     STOREY - FLOOR_T, STOREY, fm, floor=True))

    # Spine wall: steps up with flight A, so neither flight can see the other.
    for k in range(steps):
        objs.append(slab(f"Spine{k}", ax1, bx0, y_foot + k * going,
                         y_foot + (k + 1) * going, 0.0, (k + 1) * rise + 1.05, w))
    objs.append(slab("SpineTop", ax1, bx0, y_head, s - WALL_T, 0.0, STOREY / 2 + 1.05, w))

    # Perimeter. The -Y wall carries both the lower entry and the upper exit, which
    # is what makes this piece the join between two storeys of the grid.
    objs += wall_run("WallS", 0, s, 0, WALL_T, w, 0.0, top_h, [
        (ax0, ax1, 0.0, CLEAR_H),
        (bx0, bx1, STOREY, top_h),
    ])
    objs += wall_run("WallN", 0, s, s - WALL_T, s, w, 0.0, top_h)
    objs += wall_run("WallW", 0, WALL_T, WALL_T, s - WALL_T, w, 0.0, top_h)
    objs += wall_run("WallE", s - WALL_T, s, WALL_T, s - WALL_T, w, 0.0, top_h)
    return objs


