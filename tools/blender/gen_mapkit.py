def build_junction_cross() -> list:
    """A 4-way. Two of these in a zone make a loop unavoidable (§12)."""
    objs: list = []
    c, st = mat("Ceiling_Structure"), mat("Trim_Steel")
    corridor_floor(objs, 0, GRID, 0, GRID, mat("Floor_Concrete"), drain_every=99.0)
    objs.append(slab("Ceil", 0, GRID, 0, GRID, CLEAR_H, CLEAR_H + CEIL_T, c, trim=False))
    for nx, ny in ((0, 0), (1, 0), (0, 1), (1, 1)):
        corner_pier(objs, 0.0 if nx == 0 else GRID - WALL_T,
                    0.0 if ny == 0 else GRID - WALL_T)

    # Cross beams: the 4-way has no walls at all, so the ceiling needs carrying and
    # the junction needs something for a flashlight to catch (§05). Two beams and a
    # coffer between them turn the busiest tile in the kit into a landmark, which
    # matters because §12 makes junctions the places a chase is decided.
    for tag, x0, x1, y0, y1 in (("X", 0, GRID, GRID / 2 - 0.11, GRID / 2 + 0.11),
                                ("Y", GRID / 2 - 0.11, GRID / 2 + 0.11, 0, GRID)):
        objs.append(slab(f"Beam{tag}", x0, x1, y0, y1, CLEAR_H - 0.26, CLEAR_H, c,
                         trim=False))
    for x0, y0 in ((WALL_T, WALL_T), (GRID / 2 + 0.11, WALL_T),
                   (WALL_T, GRID / 2 + 0.11), (GRID / 2 + 0.11, GRID / 2 + 0.11)):
        objs.append(slab(f"Coffer{x0:.1f}_{y0:.1f}", x0 + 0.05,
                         x0 + GRID / 2 - WALL_T - 0.16, y0 + 0.05,
                         y0 + GRID / 2 - WALL_T - 0.16,
                         CLEAR_H - 0.05, CLEAR_H, c, trim=False))

    # Services cross overhead and meet in a box. A pipe run that simply ends at
    # every junction is what makes a kit's corridors look disconnected.
    objs.append(pipe("PipeY", "Y", 0.0, GRID, WALL_T + detail.PIPE_LANE,
                     detail.PIPE_Z, detail.PIPE_R, st))
    objs.append(pipe("PipeX", "X", 0.0, GRID, GRID - WALL_T - detail.TRAY_LANE,
                     detail.PIPE_Z - 0.20, 0.045, st, sides=6))
    objs.append(slab("PipeCross", WALL_T + detail.PIPE_LANE - 0.10,
                     WALL_T + detail.PIPE_LANE + 0.10,
                     GRID - WALL_T - detail.TRAY_LANE - 0.10,
                     GRID - WALL_T - detail.TRAY_LANE + 0.10,
                     detail.PIPE_Z - 0.26, detail.PIPE_Z + 0.10, st))
    return objs


def build_dead_end() -> list:
    """A 2.5 x 5 m dead end whose reward is part of the geometry.

    §12 wants 막힌 길 비율 20~25% and pairs it with 막힌 길 보상 = 전리품 · 자재,
    reason: "위험을 감수할 이유". A cap with no reward is the failure mode this piece
    exists to make impossible — the loot plinth and the alcove ship with it.
    """
    depth = 2 * GRID
    objs: list = []
    w, c, st = mat("Wall_Structure"), mat("Ceiling_Structure"), mat("Trim_Steel")
    corridor_floor(objs, 0, GRID, 0, depth, mat("Floor_Concrete"))
    objs += framed_ceiling("Ceil", 0, GRID, 0, depth, CLEAR_H, span="X", slab_t=CEIL_T)
    objs += dressed_wall("WallW", 0, WALL_T, 0, depth, "+X", CLEAR_H,
                         pilaster_pitch=GRID, pilaster_phase=GRID / 2, wear_seed=101)
    objs += dressed_wall("WallE", GRID - WALL_T, GRID, 0, depth, "-X", CLEAR_H,
                         pilaster_pitch=GRID, pilaster_phase=GRID / 2, wear_seed=103)

    # North wall, built around a 1.25 x 0.22 x 1.35 m alcove over a 0.55 m shelf.
    # The alcove is cut as an opening in a dressed wall so the skirting, damp band
    # and rail return into the reveal rather than stopping dead at the hole.
    ny0, ny1 = depth - 0.30, depth
    objs += dressed_wall("N", 0, GRID, ny0, ny1, "-Y", CLEAR_H,
                         openings=[(0.70, 1.95, 0.55, 1.90)],
                         pilaster_pitch=0.0, wear_seed=107)
    objs.append(slab("N_Back", 0.70, 1.95, ny1 - 0.08, ny1, 0.0, CLEAR_H, w, trim=False))
    objs.append(slab("N_Shelf", 0.70, 1.95, ny0 - 0.05, ny1 - 0.08, 0.48, 0.55,
                     mat("Trim_Painted")))
    # Two more shelves and their brackets inside the niche. A 1.25 x 1.35 m
    # recessed rectangle lit head-on is a bright blank panel; shelves break it into
    # bands and give the loot somewhere it plausibly came from.
    for k, z in enumerate((1.02, 1.48)):
        objs.append(slab(f"N_Rack{k}", 0.74, 1.91, ny0 - 0.02, ny1 - 0.08,
                         z, z + 0.035, st, raw=True))
        for j, cx in enumerate((0.80, 1.85)):
            objs.append(slab(f"N_Brk{k}{j}", cx - 0.025, cx + 0.025,
                             ny1 - 0.30, ny1 - 0.08, z - 0.16, z, st, raw=True))
    # A cased surround, so a beam finds the alcove from the far end of the corridor.
    # §12 pairs 막힌 길 with 보상 "위험을 감수할 이유" — an unmarked reward is not one.
    objs += opening_frame("N_Case", wall_of(0, GRID, ny0, ny1, "-Y"),
                          0.70, 1.95, 1.90, width=0.075)
    # The plinth: where the 전리품 sits. An open steel rack rather than a solid
    # block — a plain box lit head-on by a torch reads as a white rectangle with no
    # depth, and this is the object §12's 막힌 길 보상 rule exists to make the player
    # walk into a dead end for. Legs, rails and a slatted deck give it a silhouette
    # and let the beam pass through it, which is what makes it look like an object
    # in a room rather than a shape painted on the floor.
    px0, px1 = 0.86, 1.79
    py0, py1 = depth - 1.08, depth - 0.47
    deck = 0.60
    for k, (lx, ly) in enumerate(((px0, py0), (px1 - 0.07, py0),
                                  (px0, py1 - 0.07), (px1 - 0.07, py1 - 0.07))):
        objs.append(slab(f"PlinthLeg{k}", lx, lx + 0.07, ly, ly + 0.07,
                         0.0, deck, st))
    for k, z in enumerate((0.16, 0.44)):
        objs.append(slab(f"PlinthRailA{k}", px0, px1, py0, py0 + 0.035, z, z + 0.055,
                         st, raw=True))
        objs.append(slab(f"PlinthRailB{k}", px0, px1, py1 - 0.035, py1, z, z + 0.055,
                         st, raw=True))
    objs.append(slab("PlinthFrame", px0 - 0.03, px1 + 0.03, py0 - 0.03, py1 + 0.03,
                     deck, deck + 0.045, st))
    for k in range(5):
        sy = py0 + (k + 0.5) * (py1 - py0) / 5.0
        objs.append(slab(f"PlinthSlat{k}", px0, px1, sy - 0.045, sy + 0.045,
                         deck + 0.045, deck + 0.065, st, raw=True))

    corridor_services(objs, "Y", 0.0, depth - 0.30, WALL_T, GRID - WALL_T)
    east = wall_of(GRID - WALL_T, GRID, 0, depth, "-X")
    objs += wall_vent("VentE", east, depth - 1.4, 2.10)
    objs += junction_box("JBoxE", east, 1.6, 1.55, drop_to=0.20)
    objs += conduit_along("ConduitW", wall_of(0, WALL_T, 0, depth, "+X"),
                          0.0, depth - 0.30, count=2)
    return objs


