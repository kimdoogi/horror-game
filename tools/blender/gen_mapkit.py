# ── Floor tiles: §12's gameplay channel ─────────────────────────────────────
#
# §12 is explicit that this is a systems decision, not an art one, and that the
# boundary must be unambiguous. §05 says the game is dark and lit by a narrow
# flashlight cone, so colour cannot be the whole signal — every tile therefore has
# distinct *relief* as well, and every relief pattern keeps its contact plane at
# exactly z = 0 so tiles of different materials butt together without a step.

TILE = 2 * GRID  # 5.0 m square


def build_tile_wood() -> list:
    """Zone A — 나무 / 삐걱. Boarding with staggered butt joints and lifted boards.

    §12 makes this a gameplay channel, not a look: the Listener names the zone from
    the footstep, and §05 says the player is reading a dark room through a narrow
    cone. So the relief has to be recognisable at a glance and unmistakable against
    the other four. Boards on their own were not — ten parallel strips of identical
    height read as a striped plane. Staggered butt joints break the strips into
    *boards*, and the ±1.5 mm level variation catches the beam differently on each
    one, which is what makes a timber floor look timber before any texture lands.
    """
    rng = random.Random(0x0A0D)
    objs: list = []
    m = mat("Floor_Wood")
    objs.append(slab("Base", 0, TILE, 0, TILE, -FLOOR_T, -0.026, m, floor=True))
    n = 10
    pitch = TILE / n
    for k in range(n):
        x0 = k * pitch + 0.010
        x1 = x0 + pitch - 0.020
        # Butt joints staggered per run, never aligned across neighbouring boards.
        cuts = sorted(rng.uniform(0.9, TILE - 0.9) for _ in range(rng.randint(1, 2)))
        edges = [0.0] + cuts + [TILE]
        for j in range(len(edges) - 1):
            y0 = edges[j] + (0.012 if j else 0.0)
            y1 = edges[j + 1] - (0.012 if j < len(edges) - 2 else 0.0)
            top = -rng.uniform(0.0, 0.0030)
            objs.append(slab(f"Plank{k}_{j}", x0, x1, y0, y1, -0.026, top, m, floor=True))
    # Two lifted boards: the ones that would creak. §12 gives zone A 삐걱.
    for k, (bx, by) in enumerate(((1.6, 1.2), (3.4, 3.7))):
        objs.append(slab(f"Lifted{k}", bx, bx + pitch - 0.020, by, by + 1.1,
                         -0.026, -0.0005, m, floor=True))
    return objs


def build_tile_tile() -> list:
    """Zone B — 타일 / 딱딱, 반향. A 10 x 10 grid of 0.5 m tiles with grout lines.

    §12's 반향 zone. The tiles are dead flat by nature, so the readable feature is
    the *grid* — and a perfect grid reads as a texture rather than a surface. A
    handful of missing and sunken tiles gives the beam somewhere to break, and
    tells the player this floor has been walked on for a long time.
    """
    rng = random.Random(0x71E1)
    objs: list = []
    m = mat("Floor_Tile")
    objs.append(slab("Base", 0, TILE, 0, TILE, -FLOOR_T, -0.020, m, floor=True))
    n = 10
    pitch = TILE / n
    for i in range(n):
        for j in range(n):
            roll = rng.random()
            if roll < 0.035:
                continue          # lifted tile: the bed shows through
            top = -0.0025 if roll < 0.10 else 0.0   # sunken, still walkable
            objs.append(slab(f"T{i}_{j}", i * pitch + 0.011, (i + 1) * pitch - 0.011,
                             j * pitch + 0.011, (j + 1) * pitch - 0.011,
                             -0.020, top, m, floor=True))
    return objs


def build_tile_gravel() -> list:
    """Zone C — 자갈 / 부스럭. A jittered surface, seeded so rebuilds are identical.

    Built with bmesh rather than boxes: an irregular walking surface is what makes
    gravel unmistakable in a flashlight cone, and it costs a fraction of the
    triangles that a few hundred pebble boxes would. The perimeter ring is pinned to
    z = 0 so the tile still butts flush against every other material.
    """
    rng = random.Random(0xC0FFEE)
    n = 20
    step = TILE / n
    mesh = bpy.data.meshes.new("F_GravelMesh")
    obj = bpy.data.objects.new("F_GravelTop", mesh)
    bpy.context.collection.objects.link(obj)

    bm = bmesh.new()
    grid = []
    for i in range(n + 1):
        row = []
        for j in range(n + 1):
            edge = i in (0, n) or j in (0, n)
            z = 0.0 if edge else -rng.uniform(0.008, 0.055)
            row.append(bm.verts.new((i * step, j * step, z)))
        grid.append(row)
    for i in range(n):
        for j in range(n):
            bm.faces.new((grid[i][j], grid[i + 1][j], grid[i + 1][j + 1], grid[i][j + 1]))

    ring = []
    for i in range(n):
        ring.append(grid[i][0])
    for j in range(n):
        ring.append(grid[n][j])
    for i in range(n, 0, -1):
        ring.append(grid[i][n])
    for j in range(n, 0, -1):
        ring.append(grid[0][j])
    bottom = [bm.verts.new((v.co.x, v.co.y, -FLOOR_T)) for v in ring]
    for k in range(len(ring)):
        nk = (k + 1) % len(ring)
        bm.faces.new((ring[k], ring[nk], bottom[nk], bottom[k]))
    bm.faces.new(tuple(reversed(bottom)))
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
    bm.to_mesh(mesh)
    bm.free()
    mesh.update()
    blendkit.assign_material(obj, mat("Floor_Gravel"))
    return [obj]


def build_tile_concrete() -> list:
    """Zone D — 콘크리트 / 둔탁. Poured bays, saw cuts, a gully and two patches.

    This tile carpets the largest zone in the map, so it is the single biggest
    visible surface in the game — and it was 60 triangles of flat plane. §05 lights
    it with one torch pointed mostly at the floor, which means a featureless slab is
    a smooth gradient the player walks across for minutes at a time with no sense of
    motion at all.

    The fix is what a real basement slab has and costs almost nothing: each poured
    bay finishes a few millimetres off its neighbour, saw cuts run between them, a
    gully sits where the falls meet, and two patched repairs break the grid. Every
    surface stays at or below z = 0 so the tile still butts flush against the
    corridors and against the other four §12 materials.
    """
    rng = random.Random(0xC047)
    objs: list = []
    m = mat("Floor_Concrete")
    objs.append(slab("Base", 0, TILE, 0, TILE, -FLOOR_T, -0.016, m, floor=True))
    levels = (0.0, -0.0035, -0.0015, -0.0055)
    for i in range(2):
        for j in range(2):
            objs.append(slab(f"Slab{i}{j}", i * GRID + 0.014, (i + 1) * GRID - 0.014,
                             j * GRID + 0.014, (j + 1) * GRID - 0.014,
                             -0.016, levels[i * 2 + j], m, floor=True))
    # Saw-cut control joints on a 1.25 m grid inside each bay: the lines that give
    # a big floor a scale and a direction under a moving beam.
    for k in range(1, 4):
        if k == 2:
            continue          # the 2.5 m line is already the bay joint
        a = k * TILE / 4.0
        objs.append(slab(f"CutX{k}", 0, TILE, a - 0.010, a + 0.010,
                         -0.016, -0.0045, m, floor=True))
        objs.append(slab(f"CutY{k}", a - 0.010, a + 0.010, 0, TILE,
                         -0.016, -0.0045, m, floor=True))
    objs += floor_drain("Gully", TILE / 2, TILE / 2, at_z=-0.008)
    # Patched repairs: a cut-out refilled later, proud of the surface it interrupts.
    for k in range(2):
        px = rng.uniform(0.5, TILE - 1.6)
        py = rng.uniform(0.5, TILE - 1.4)
        objs.append(slab(f"Patch{k}", px, px + rng.uniform(0.8, 1.4),
                         py, py + rng.uniform(0.7, 1.2), -0.016, -0.0008,
                         mat("Wall_Dado"), floor=True))
    return objs


def build_tile_metal() -> list:
    """계단 — 금속 / 울림. Checker plate with raised tread ribs.

    §12 gives 금속 to stairs alone, so this tile is for stair landings, catwalks and
    plant rooms. The cross-hatched ribs are the loudest relief in the kit, which is
    the point: metal is the surface the Listener must never confuse with the four
    zone materials.
    """
    objs: list = []
    m, st = mat("Floor_Metal"), mat("Trim_Steel")
    objs.append(slab("Base", 0, TILE, 0, TILE, -FLOOR_T, -0.020, m, floor=True))
    for i in range(2):
        for j in range(2):
            objs.append(slab(f"Plate{i}{j}", i * GRID + 0.010, (i + 1) * GRID - 0.010,
                             j * GRID + 0.010, (j + 1) * GRID - 0.010,
                             -0.020, -0.006, m, floor=True))
    n = 12
    pitch = TILE / n
    for k in range(n):
        c = (k + 0.5) * pitch
        objs.append(slab(f"RibX{k}", 0, TILE, c - 0.035, c + 0.035, -0.006, 0.0,
                         m, floor=True))
        objs.append(slab(f"RibY{k}", c - 0.035, c + 0.035, 0, TILE, -0.006, 0.0,
                         m, floor=True))
    # Countersunk bolts at every plate corner. Sixteen tiny discs, and they are what
    # turn "a hatched surface" into "steel plates someone screwed down" — which is
    # the reading §12 needs, since 금속 is the one surface that must never be
    # confused with the four zone materials.
    for i in range(3):
        for j in range(3):
            bx, by = i * GRID, j * GRID
            bx = min(max(bx, 0.10), TILE - 0.10)
            by = min(max(by, 0.10), TILE - 0.10)
            objs.append(slab(f"Bolt{i}{j}", bx - 0.032, bx + 0.032,
                             by - 0.032, by + 0.032, -0.006, 0.0, st, floor=True))
    return objs


def build_floor_boundary() -> list:
    """The material change itself, made a piece. §12: "재질 경계를 명확히 할 것."

    The Listener reads the monster's position from which surface its feet land on
    (§04, §12), so an ambiguous boundary is not a cosmetic flaw — it is a broken
    ability. This 5.0 x 2.5 m piece puts two surfaces edge to edge across a 0.20 m
    recessed channel, 0.03 m deep: the seam casts a shadow line at any flashlight
    angle, and a footstep can only ever sample one side of it or the other.

    The two slots ship as ``Floor_Concrete`` and ``Floor_Wood`` (§12's D/A pair) and
    are meant to be reassigned per adjacency in Unity — the contractual names make
    that a rename, not a re-export.
    """
    objs: list = []
    a, b = mat("Floor_Concrete"), mat("Floor_Wood")
    mid = GRID / 2.0
    objs.append(slab("SideA", 0, TILE, 0, mid - 0.10, -FLOOR_T, 0.0, a, floor=True))
    objs.append(slab("Channel", 0, TILE, mid - 0.10, mid + 0.10, -FLOOR_T, -0.030,
                     a, floor=True))
    objs.append(slab("SideB", 0, TILE, mid + 0.10, GRID, -FLOOR_T, 0.0, b, floor=True))
    return objs


