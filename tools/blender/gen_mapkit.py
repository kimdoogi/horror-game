# ── Build pipeline ──────────────────────────────────────────────────────────


def build_piece(spec: PieceSpec) -> tuple[blendkit.AssetReport, list]:
    """Builds, joins, verifies and exports one piece in a clean scene.

    Objects are sorted into four bevel groups by name prefix. One chamfer width
    cannot serve a 0.15 m wall and a 0.04 m skirting — a 12 mm offset removes most
    of the skirting and inverts anything thinner — so structure gets 12 mm, fine
    trim gets 4 mm, and pipes and floors get none. ``gen_mapkit_detail.slab``
    assigns the prefix automatically by thickness, which is what stops a new
    moulding quietly collapsing the first time someone adds one.
    """
    blendkit.reset_scene()
    bpy.context.scene.cursor.location = (0.0, 0.0, 0.0)

    objs = spec.build()
    if not objs:
        raise AssertionError(f"{spec.name}: builder produced no objects")

    groups = {detail.PREFIX_FLOOR: [], detail.PREFIX_TRIM: [], detail.PREFIX_RAW: [],
              "": []}
    for o in objs:
        for prefix in (detail.PREFIX_FLOOR, detail.PREFIX_TRIM, detail.PREFIX_RAW):
            if o.name.startswith(prefix):
                groups[prefix].append(o)
                break
        else:
            groups[""].append(o)

    parts = []
    for prefix, bevel_w in (("", BEVEL_W), (detail.PREFIX_TRIM, detail.BEVEL_TRIM),
                            (detail.PREFIX_RAW, 0.0), (detail.PREFIX_FLOOR, 0.0)):
        members = groups[prefix]
        if not members:
            continue
        joined = blendkit.join(members, f"{spec.name}_{prefix or 'S'}")
        if bevel_w > 0.0:
            blendkit.bevel(joined, bevel_w, 1)
        parts.append(joined)

    piece = blendkit.join(parts, spec.name)
    blendkit.triangulate(piece)

    bpy.ops.object.select_all(action="DESELECT")
    piece.select_set(True)
    bpy.context.view_layer.objects.active = piece
    bpy.ops.object.origin_set(type="ORIGIN_CURSOR")
    # Origin is now (0, 0, 0), so object space is world space and the box
    # projection lands the same texel grid on every piece in the kit.
    detail.uv_box_project(piece, UV_METRES_PER_TILE)

    slots = [m.name if m else "<none>" for m in piece.data.materials]
    path = blendkit.out_path("MapKit", spec.name + ".fbx")
    blendkit.export_fbx(path, [piece])

    report = blendkit.describe(path)
    blendkit.assert_asset(report, min_vertices=8, max_triangles=spec.max_tris,
                          max_dimension=25.0)
    verify_piece(spec, report)
    blendkit.print_report(report)
    return report, slots


def verify_piece(spec: PieceSpec, report: blendkit.AssetReport) -> None:
    """The §12 checks. A piece that fails one of these cannot be placed safely."""
    sx, sy, sz = report.size
    lo = report.bounds_min

    if abs(lo[0]) > 1e-4 or abs(lo[1]) > 1e-4:
        raise AssertionError(
            f"{spec.name}: origin is not the min-X/min-Y corner — bounds_min="
            f"({lo[0]:.4f}, {lo[1]:.4f}). A level placed on grid coordinates would drift.")

    if max(sx, sy) > MAX_STRAIGHT + 1e-4:
        raise AssertionError(
            f"{spec.name}: footprint {sx:.2f} x {sy:.2f} m exceeds §12's 20 m — "
            "'직선 통로 최대 20m, 넘으면 주자가 죽는다'.")

