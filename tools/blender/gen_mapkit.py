#!/usr/bin/env python3
"""Generates the modular map kit — the pieces §12's rules are built out of.

Run headless::

    /Applications/Blender.app/Contents/MacOS/Blender --background --factory-startup \\
        --python tools/blender/gen_mapkit.py

Outputs one FBX per piece into ``Assets/Models/MapKit/`` plus
``MapKit.manifest.json`` describing every footprint, dock point and floor slot.

WHY THIS KIT EXISTS
-------------------
§12 opens with **"맵은 아트가 아니라 시스템이다"** and then derives every dimension
from §06's speeds. That means the pieces themselves are the enforcement mechanism:
if the only 직선 통로 a designer can place is 10 m long, no assembled level can
violate §12's "직선 통로 최대 20m — 넘으면 주자가 죽는다".

So each dimension below is a *consequence*, not a taste:

* **S-corridor legs 10 m.** §12: "10m 구간 2개의 S자 통로 하나면 해제가 성립한다.
  이것이 맵의 기본 단위다." 20 m of path / 4.8 m/s = 4.17 s > the 3 s of broken
  line of sight §06 requires. ``SCorridor_Unit_10m_x2`` ships that whole unit as one
  piece so it cannot be mis-composed, and ``Corridor_Corner_L`` + the straights let
  it be rebuilt by hand.
* **Nothing longer than 20 m.** The longest straight run in the kit is the 10 m
  straight; the widest footprint is the 20 m hall, whose 20 m sight line is
  *required* by §12 (개방 공간 시야 15~25m), not merely tolerated.
* **Loops.** §12: "순환로 개수 — 구역당 1+, 전체 3+ / 트리 구조는 사형선고." A tree
  graph cannot be built from a kit whose junctions are a T and a 4-way, so both ship.
* **Dead ends carry a reward.** §12 wants 20-25% dead ends "위험을 감수할 이유"로.
  ``DeadEnd_Cap`` therefore has a loot plinth and a lit alcove built in — the reward
  is part of the geometry, not level dressing someone may forget.
* **Floor material is a gameplay channel.** §12: "구역별로 바닥 재질이 달라야 청음사가
  위치를 판별할 수 있다. 아트 결정이 아니라 시스템 결정이다. 재질 경계를 명확히 할 것."
  All five surfaces ship with the contractual ``Floor_Wood`` / ``Floor_Tile`` /
  ``Floor_Gravel`` / ``Floor_Concrete`` / ``Floor_Metal`` names *and* with distinct
  surface relief, because §05 says the game is dark — colour alone will not read in
  a flashlight cone, so the boundary is made geometric as well.
* **Observation posts.** §04's Observer works at 15 m and §12 says without posts
  "관측자는 죽으러 가야 한다". Two ship: a 15 m raised gallery and a barred-window
  alcove whose bar gaps are too narrow for the monster.
* **Doors at bottlenecks.** §04's Engineer locks them; §12 allows 구역당 1~2개.
  The leaf is a separate piece so one doorway can be locked and another left open.

GRID AND ORIGIN — the two things a level assembler depends on
-------------------------------------------------------------
* **Grid: 2.5 m**, horizontally, on both axes. Every §12 number is a multiple of it
  (5, 10, 15, 20, 17.5), so every piece footprint is an exact multiple and the
  script asserts it.
* **Origin: the minimum-X / minimum-Y corner of the footprint, at the floor's top
  surface (z = 0).** Placing a piece at grid coordinate (i, j) therefore means
  translating to (i × 2.5, j × 2.5, 0) with no offset arithmetic, and the walkable
  surface is always exactly y = 0 in Unity. The script asserts
  ``bounds_min.x == bounds_min.y == 0`` for every piece.
* Two pieces are **props, not tiles**: ``Door_Panel_Lockable`` (positioned by its
  hinge, which is its origin) and ``WallPanel_Electrical``. They are exempt from the
  grid assertion and say so in the table.

CROSS-SECTION — why the corridor is 2.20 m × 3.00 m clear
---------------------------------------------------------
* §08's w5 궤짝 is a **two-person carry** ("2인 운반"), and §08 calls two players
  walking a chest down a narrow corridor "최고의 순간". Two player capsules side by
  side plus the chest need ≈1.8 m; 2.20 m clear passes it while still being narrow
  enough to be the 섬광수's stage (§12: "넓은 곳에서는 괴물이 우회한다").
* The monster is 2.34 m tall and 0.93 m across the shoulders as generated by
  ``gen_monster_model.py`` (§12 budgets ~1.2 m). 3.00 m clear height and 2.20 m
  clear width both pass with margin, so §06's speeds are never limited by geometry.
* Door hardware (hinge pintles) is the tightest point at 2.08 m clear. Still above
  the two-person carry requirement; called out in the report rather than hidden.
"""

