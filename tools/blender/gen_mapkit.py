def build_s_corridor() -> list:
    """§12's 맵의 기본 단위 as a single piece: two 10 m legs, 20 m of path.

    §12 proves this is the only reliable 어그로 해제 structure::

        구간 L = 10m,  총 20m
        통과 시간 = 20 / 4.8 = 4.2초  >=  3초  ✅

    Centreline, measured: (1.25, 0) -> (1.25, 8.75) -> (3.75, 8.75) -> (3.75, 17.5)
    = 8.75 + 2.50 + 8.75 = **20.00 m** exactly. Neither leg's straight sight line
    exceeds 10 m, and entry and exit are on opposite ends so it *connects* two
    places rather than being a hairpin — which is what makes it usable as the
    map's base unit rather than a set piece.
    """
    total_y = 17.5
    objs: list = []
    st, fl = mat("Trim_Steel"), mat("Floor_Concrete")

    # Leg A occupies x[0, 2.5] y[0, 10]; leg B occupies x[2.5, 5.0] y[7.5, 17.5].
    corridor_floor(objs, 0, GRID, 0, S_LEG, fl)
    corridor_floor(objs, GRID, 2 * GRID, S_LEG - GRID, total_y, fl)
    objs += framed_ceiling("CeilA", 0, GRID, 0, S_LEG, CLEAR_H, span="X", slab_t=CEIL_T)
    objs += framed_ceiling("CeilB", GRID, 2 * GRID, S_LEG - GRID, total_y, CLEAR_H,
                           span="X", slab_t=CEIL_T)

    # Leg A: west wall full length, east wall stops at the jog, north wall closes it.
    objs += dressed_wall("A_WallW", 0, WALL_T, 0, S_LEG, "+X", CLEAR_H,
                         pilaster_pitch=GRID, pilaster_phase=GRID / 2, wear_seed=61)
    objs += dressed_wall("A_WallE", GRID - WALL_T, GRID, 0, S_LEG - GRID, "-X", CLEAR_H,
                         pilaster_pitch=GRID, pilaster_phase=GRID / 2, wear_seed=67)
    objs += dressed_wall("A_WallN", 0, GRID, S_LEG - WALL_T, S_LEG, "-Y", CLEAR_H,
                         pilaster_pitch=0.0, wear_seed=71)
    # Leg B: south wall closes it, west wall starts above the jog.
    objs += dressed_wall("B_WallS", GRID, 2 * GRID, S_LEG - GRID, S_LEG - GRID + WALL_T,
                         "+Y", CLEAR_H, pilaster_pitch=0.0, wear_seed=73)
    objs += dressed_wall("B_WallW", GRID, GRID + WALL_T, S_LEG, total_y, "+X", CLEAR_H,
                         pilaster_pitch=GRID, pilaster_phase=GRID / 2, wear_seed=79)
    objs += dressed_wall("B_WallE", 2 * GRID - WALL_T, 2 * GRID, S_LEG - GRID, total_y,
                         "-X", CLEAR_H, pilaster_pitch=GRID, pilaster_phase=GRID / 2,
                         wear_seed=83)

    corridor_services(objs, "Y", 0.0, S_LEG - GRID, WALL_T, GRID - WALL_T)
    corridor_services(objs, "Y", S_LEG, total_y, GRID + WALL_T, 2 * GRID - WALL_T)
    # The jog itself: the services cross it overhead, which is what makes the two
    # legs read as one corridor that bends rather than two corridors that meet.
    objs.append(pipe("PipeJog", "X", WALL_T + detail.PIPE_LANE,
                     GRID + WALL_T + detail.PIPE_LANE, S_LEG - GRID / 2,
                     detail.PIPE_Z, detail.PIPE_R, st))

    objs += wall_vent("VentA", wall_of(0, WALL_T, 0, S_LEG, "+X"), 4.4, 2.10)
    objs += wall_vent("VentB", wall_of(2 * GRID - WALL_T, 2 * GRID, S_LEG - GRID,
                                       total_y, "-X"), 13.4, 2.10)
    objs += junction_box("JBoxA", wall_of(0, WALL_T, 0, S_LEG, "+X"), 7.1, 1.55,
                         drop_to=0.20)
    return objs


def corner_pier(objs: list, x0: float, y0: float, height: float = CLEAR_H) -> None:
    """A junction corner post with a base, a nosing and a capital.

    A junction has almost no wall, so the four posts *are* the architecture — they
    carry the whole read of the space. §12 needs junctions everywhere (순환로 구역당
    1+, 전체 3+; "트리 구조는 사형선고"), which means a player sees these constantly,
    so a bare 0.15 m square extrusion is the kit's most-repeated failure. The
    nosing is the part that matters: a chamfered vertical strip on the exposed
    arris catches the beam edge-on from any approach angle.
    """
    w, tp = mat("Wall_Structure"), mat("Trim_Painted")
    x1, y1 = x0 + WALL_T, y0 + WALL_T
    tag = f"{x0:.0f}_{y0:.0f}"
    # Mouldings grow *into* the cell only. A pilaster on a corridor wall may
    # project towards the room; a junction post sits on the piece boundary, and
    # anything overhanging it would put the piece's measured footprint outside its
    # grid cell — which verify_piece rejects, because the assembler places pieces
    # on the grid blind and a 75 mm overhang would collide with the next tile.
    ix = 1.0 if x0 <= 1e-6 else -1.0
    iy = 1.0 if y0 <= 1e-6 else -1.0

    def grown(e: float) -> tuple[float, float, float, float]:
        return (x0 if ix > 0 else x0 - e, x1 + e if ix > 0 else x1,
                y0 if iy > 0 else y0 - e, y1 + e if iy > 0 else y1)

    objs.append(slab(f"Post{tag}", x0, x1, y0, y1, 0.0, height, w, trim=False))
    bx0, bx1, by0, by1 = grown(0.055)
    objs.append(slab(f"PostBase{tag}", bx0, bx1, by0, by1, 0.0, detail.SKIRT_H, tp))
    nx0, nx1, ny0, ny1 = grown(0.030)
    objs.append(slab(f"PostNose{tag}", nx0, nx1, ny0, ny1,
                     detail.SKIRT_H, detail.DADO_TOP, mat("Wall_Dado")))
    rx0, rx1, ry0, ry1 = grown(0.060)
    objs.append(slab(f"PostRail{tag}", rx0, rx1, ry0, ry1,
                     detail.DADO_TOP, detail.RAIL_TOP, tp))
    cx0, cx1, cy0_, cy1_ = grown(0.085)
    objs.append(slab(f"PostCap{tag}", cx0, cx1, cy0_, cy1_,
                     height - 0.62, height - 0.44, tp))


