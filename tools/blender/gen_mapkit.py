def mat(key: str) -> bpy.types.Material:
    """Creates or reuses a material. Safe to call after every reset_scene()."""
    return blendkit.make_material(MAT_SPECS[key])


# ── Low-level builders ──────────────────────────────────────────────────────


def slab(name: str, x0: float, x1: float, y0: float, y1: float,
         z0: float, z1: float, material: bpy.types.Material,
         floor: bool = False) -> bpy.types.Object:
    """A box given as an axis-aligned extent rather than centre+size.

    Every dimension in §12 is expressed as "from here to there", so building from
    extents is the only way to keep the script readable against the design doc.

    `floor=True` prefixes the name with ``F_``, which excludes it from the bevel
    pass — a 12 mm chamfer on a walkable surface would open a light-leaking groove
    at every tile seam.
    """
    sx, sy, sz = x1 - x0, y1 - y0, z1 - z0
    if min(sx, sy, sz) <= 1e-6:
        raise ValueError(f"{name}: degenerate box {sx:.4f}x{sy:.4f}x{sz:.4f}")
    obj = blendkit.add_box(
        ("F_" if floor else "") + name,
        (sx, sy, sz),
        ((x0 + x1) / 2.0, (y0 + y1) / 2.0, (z0 + z1) / 2.0),
    )
    blendkit.assign_material(obj, material)
    return obj


def wall_run(name: str, x0: float, x1: float, y0: float, y1: float,
             material: bpy.types.Material, z0: float = 0.0, z1: float = CLEAR_H,
             openings: Sequence[tuple[float, float, float, float]] = ()) -> list:
    """A wall panel with holes in it, emitted as solid segments, sills and heads.

    `openings` are ``(a0, a1, h0, h1)`` in world coordinates along the wall's long
    axis. Doorways and the barred window are all cut this way so the opening width
    is a stated number rather than an accident of overlapping boxes.
    """
    parts: list = []
    horizontal = (x1 - x0) >= (y1 - y0)
    a0, a1 = (x0, x1) if horizontal else (y0, y1)

    def emit(pa0: float, pa1: float, pz0: float, pz1: float, tag: str) -> None:
        if pa1 - pa0 <= 1e-6 or pz1 - pz0 <= 1e-6:
            return
        if horizontal:
            parts.append(slab(f"{name}_{tag}", pa0, pa1, y0, y1, pz0, pz1, material))
        else:
            parts.append(slab(f"{name}_{tag}", x0, x1, pa0, pa1, pz0, pz1, material))

    cursor = a0
    for i, (oa0, oa1, oh0, oh1) in enumerate(sorted(openings)):
        emit(cursor, oa0, z0, z1, f"seg{i}")
        emit(oa0, oa1, z0, oh0, f"sill{i}")
        emit(oa0, oa1, oh1, z1, f"head{i}")
        cursor = max(cursor, oa1)
    emit(cursor, a1, z0, z1, "segE")
    return parts


def corbels(objs: list, length_axis: str, span: float, material: bpy.types.Material,
            inner_a: float, inner_b: float) -> None:
    """Ceiling brackets every 2.5 m.

    §05 makes the flashlight the only light source, and a flat 2.20 m wall gives its
    cone nothing to break on. These sit at 2.20-2.60 m — above head height, so the
    2.20 m walking width the §08 chest carry needs is untouched.
    """
    n = max(1, int(round(span / GRID)))
    for k in range(n):
        c = k * GRID + GRID / 2.0
        if length_axis == "Y":
            objs.append(slab(f"CorbelA{k}", inner_a, inner_a + 0.10, c - 0.15, c + 0.15,
                             2.20, 2.60, material))
            objs.append(slab(f"CorbelB{k}", inner_b - 0.10, inner_b, c - 0.15, c + 0.15,
                             2.20, 2.60, material))
        else:
            objs.append(slab(f"CorbelA{k}", c - 0.15, c + 0.15, inner_a, inner_a + 0.10,
                             2.20, 2.60, material))
            objs.append(slab(f"CorbelB{k}", c - 0.15, c + 0.15, inner_b - 0.10, inner_b,
                             2.20, 2.60, material))


# ── Corridors ───────────────────────────────────────────────────────────────


def build_straight(length: float) -> Callable[[], list]:
    """A straight corridor of `length` m.

    §12 caps 직선 통로 at 20 m ("넘으면 주자가 죽는다"), so the kit's longest straight
    is 10 m — half the ceiling. Two 10 m pieces butted end to end reach exactly the
    limit and nothing in the kit can exceed it.
    """
    def build() -> list:
        objs: list = []
        w, c = mat("Wall_Structure"), mat("Ceiling_Structure")
        objs.append(slab("Floor", 0, GRID, 0, length, -FLOOR_T, 0.0,
                         mat("Floor_Concrete"), floor=True))
        objs.append(slab("Ceil", 0, GRID, 0, length, CLEAR_H, CLEAR_H + CEIL_T, c))
        objs.append(slab("WallW", 0, WALL_T, 0, length, 0.0, CLEAR_H, w))
        objs.append(slab("WallE", GRID - WALL_T, GRID, 0, length, 0.0, CLEAR_H, w))
        corbels(objs, "Y", length, w, WALL_T, GRID - WALL_T)
        return objs
    return build


def build_corner_l() -> list:
    """A 90° turn in one 2.5 m cell, open on -Y and +X.

    Four of these plus the straights rebuild §12's S-corridor by hand:
    corner + 5 m + 2.5 m = a 10 m leg, exactly.
    """
    objs: list = []
    w, c = mat("Wall_Structure"), mat("Ceiling_Structure")
    objs.append(slab("Floor", 0, GRID, 0, GRID, -FLOOR_T, 0.0,
                     mat("Floor_Concrete"), floor=True))
    objs.append(slab("Ceil", 0, GRID, 0, GRID, CLEAR_H, CLEAR_H + CEIL_T, c))
    objs.append(slab("WallW", 0, WALL_T, 0, GRID, 0.0, CLEAR_H, w))
    objs.append(slab("WallN", WALL_T, GRID, GRID - WALL_T, GRID, 0.0, CLEAR_H, w))
    # The inner corner post carries the ceiling and gives the turn a hard edge to
    # read against — the Runner has to judge this corner at 5.6 m/s (§05).
    objs.append(slab("PostSE", GRID - WALL_T, GRID, 0, WALL_T, 0.0, CLEAR_H, w))
    objs.append(slab("CornerBrace", WALL_T, WALL_T + 0.28, GRID - WALL_T - 0.28,
                     GRID - WALL_T, 2.20, CLEAR_H, w))
    return objs


def build_s_corridor() -> list:
    """§12's 맵의 기본 단위 as a single piece: two 10 m legs, 20 m of path.

    §12 proves this is the only reliable 어그로 해제 structure::

        구간 L = 10m,  총 20m
        통과 시간 = 20 / 4.8 = 4.2초  >=  3초  ✅

    Centreline, measured: (1.25, 0) -> (1.25, 8.75) -> (3.75, 8.75) -> (3.75, 17.5)
    = 8.75 + 2.50 + 8.75 = **20.00 m** exactly. Neither leg's straight sight line
    exceeds 10 m, and entry and exit are on opposite ends so it *connects* two
    places rather than being a hairpin — which is what makes it usable as the
    map's base unit rather than a set piece.
    """
    total_y = 17.5
    objs: list = []
    w, c, fl = mat("Wall_Structure"), mat("Ceiling_Structure"), mat("Floor_Concrete")

    # Leg A occupies x[0, 2.5] y[0, 10]; leg B occupies x[2.5, 5.0] y[7.5, 17.5].
    objs.append(slab("FloorA", 0, GRID, 0, S_LEG, -FLOOR_T, 0.0, fl, floor=True))
    objs.append(slab("FloorB", GRID, 2 * GRID, S_LEG - GRID, total_y, -FLOOR_T, 0.0,
                     fl, floor=True))
    objs.append(slab("CeilA", 0, GRID, 0, S_LEG, CLEAR_H, CLEAR_H + CEIL_T, c))
    objs.append(slab("CeilB", GRID, 2 * GRID, S_LEG - GRID, total_y,
                     CLEAR_H, CLEAR_H + CEIL_T, c))

    # Leg A: west wall full length, east wall stops at the jog, north wall closes it.
    objs.append(slab("A_WallW", 0, WALL_T, 0, S_LEG, 0.0, CLEAR_H, w))
    objs.append(slab("A_WallE", GRID - WALL_T, GRID, 0, S_LEG - GRID, 0.0, CLEAR_H, w))
    objs.append(slab("A_WallN", 0, GRID, S_LEG - WALL_T, S_LEG, 0.0, CLEAR_H, w))
    # Leg B: south wall closes it, west wall starts above the jog.
    objs.append(slab("B_WallS", GRID, 2 * GRID, S_LEG - GRID, S_LEG - GRID + WALL_T,
                     0.0, CLEAR_H, w))
    objs.append(slab("B_WallW", GRID, GRID + WALL_T, S_LEG, total_y, 0.0, CLEAR_H, w))
    objs.append(slab("B_WallE", 2 * GRID - WALL_T, 2 * GRID, S_LEG - GRID, total_y,
                     0.0, CLEAR_H, w))

    corbels(objs, "Y", S_LEG - GRID, w, WALL_T, GRID - WALL_T)
    return objs


