def rot_point(px: float, py: float, rot: int, fx: float, fy: float) -> tuple[float, float]:
    """Rotates a piece-local point, re-anchored so the min corner stays at (0, 0)."""
    if rot == 0:
        return (px, py)
    if rot == 90:
        return (fy - py, px)
    if rot == 180:
        return (fx - px, fy - py)
    if rot == 270:
        return (py, fx - px)
    raise ValueError(f"rotation must be a multiple of 90°, got {rot}")


def rot_edge(edge: str, rot: int) -> str:
    nx, ny = EDGE_NORMALS[edge]
    for _ in range((rot // 90) % 4):
        nx, ny = -ny, nx
    for name, vec in EDGE_NORMALS.items():
        if vec == (round(nx), round(ny)):
            return name
    raise ValueError(edge)


def check_assembly(by_name: dict) -> tuple[list[tuple[bool, str]], dict]:
    """Assembles PROTOTYPE_LAYOUT symbolically and applies §12's checklist."""
    placed = []
    for idx, (name, cx, cy, rot, level) in enumerate(PROTOTYPE_LAYOUT):
        spec, report = by_name[name]
        fx, fy = report.size[0], report.size[1]
        wx, wy = (fy, fx) if rot in (90, 270) else (fx, fy)
        ox, oy = cx * GRID, cy * GRID
        docks = []
        for d in spec.docks:
            lx, ly = rot_point(d["centre"][0], d["centre"][1], rot, fx, fy)
            docks.append({
                "edge": rot_edge(d["edge"], rot),
                "pt": (round(ox + lx, 4), round(oy + ly, 4)),
                "width": d["width"], "height": d["height"],
                "level": level + d["level"],
            })
        placed.append({"i": idx, "name": name, "cells": (cx, cy, cx + round(wx / GRID),
                                                         cy + round(wy / GRID)),
                       "extent": (ox, oy, ox + wx, oy + wy),
                       "level": level, "docks": docks, "kind": spec.kind})

    results: list[tuple[bool, str]] = []

    off_grid = [p["name"] for p in placed
                if abs(p["extent"][2] / GRID - round(p["extent"][2] / GRID)) > 1e-6
                or abs(p["extent"][3] / GRID - round(p["extent"][3] / GRID)) > 1e-6]
    results.append((not off_grid,
                    f"all {len(placed)} placements land on the {GRID} m grid"
                    + (f" — OFF GRID: {off_grid}" if off_grid else "")))

    clashes = []
    for a in range(len(placed)):
        for b in range(a + 1, len(placed)):
            pa, pb = placed[a], placed[b]
            if abs(pa["level"] - pb["level"]) > 1e-6:
                continue
            ax0, ay0, ax1, ay1 = pa["cells"]
            bx0, by0, bx1, by1 = pb["cells"]
            if ax0 < bx1 and bx0 < ax1 and ay0 < by1 and by0 < ay1:
                clashes.append(f"{pa['name']}@{pa['cells'][:2]} vs {pb['name']}@{pb['cells'][:2]}")
    results.append((not clashes,
                    f"no two same-level pieces overlap"
                    + (f" — CLASHES: {clashes}" if clashes else "")))

    parent = list(range(len(placed)))

    def find(i: int) -> int:
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    edges = 0
    mismatched = []
    open_docks = 0
    for a in range(len(placed)):
        for da in placed[a]["docks"]:
            partner = None
            for b in range(len(placed)):
                if b == a:
                    continue
                for db in placed[b]["docks"]:
                    if (da["pt"] == db["pt"] and abs(da["level"] - db["level"]) < 1e-6
                            and db["edge"] == OPPOSITE[da["edge"]]):
                        partner = (b, db)
            if partner is None:
                open_docks += 1
                continue
            b, db = partner
            if abs(da["width"] - db["width"]) > 1e-6:
                mismatched.append(f"{placed[a]['name']} {da['width']:.2f} m vs "
                                  f"{placed[b]['name']} {db['width']:.2f} m at {da['pt']}")
            if a < b:
                edges += 1
                ra, rb = find(a), find(b)
                if ra != rb:
                    parent[ra] = rb
    results.append((not mismatched,
                    f"{edges} dock connections, every one matched in clear width "
                    f"({CLEAR_W:.2f} m)" + (f" — MISMATCH: {mismatched}" if mismatched else "")))

    components = len({find(i) for i in range(len(placed))})
    loops = edges - len(placed) + components
    results.append((loops >= 3,
                    f"independent loops = E - V + C = {edges} - {len(placed)} + {components} "
                    f"= {loops} (§12 requires 3+ map-wide; 트리 구조는 사형선고)"))

    dead_ends = sum(1 for p in placed if p["kind"] == "deadend")
    results.append((dead_ends >= 1,
                    f"{dead_ends} dead end(s) placed, each carrying a reward (§12 막힌 길 보상)"))

    posts = sum(1 for p in placed if p["kind"] == "observation")
    results.append((posts >= 1,
                    f"{posts} observation post(s) — §12 구역당 1~2개, else 관측자는 죽으러 가야 한다"))

    has_open = any(p["kind"] == "open" for p in placed)
    open_adjacent = False
    for p in placed:
        if p["kind"] != "open":
            continue
        for d in p["docks"]:
            for q in placed:
                if q["kind"] == "corridor" and any(e["pt"] == d["pt"] for e in q["docks"]):
                    open_adjacent = True
    results.append((has_open and open_adjacent,
                    "개방 공간 present and adjacent to 미로 공간 (§12: 개방만 있으면 도망칠 곳이 없고, "
                    "미로만 있으면 멀리서 어그로를 걸 수 없다)"))

    max_x = max(p["extent"][2] for p in placed)
    max_y = max(p["extent"][3] for p in placed)
    results.append((max_x <= 100.0 and max_y <= 100.0,
                    f"assembly extent {max_x:.1f} x {max_y:.1f} m, inside §12's 100 x 100 m map"))

    stats = {"pieces": len(placed), "connections": edges, "loops": loops,
             "open_docks": open_docks, "extent": [max_x, max_y],
             "dead_ends": dead_ends, "observation_posts": posts}
    return results, stats


