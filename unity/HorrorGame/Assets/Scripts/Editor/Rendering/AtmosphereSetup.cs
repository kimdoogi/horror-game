        /// <summary>
        /// Builds the project's default Volume profile and points URP at it.
        /// <para>
        /// The default profile, not a Volume in the map scene: a Volume lives in
        /// one scene and the lobby, the map and anything generated later all need
        /// the same film stock. It carries only what is constant all night —
        /// <see cref="ThreatAtmosphereDirector"/> layers §07's exposure,
        /// temperature, saturation and vignette on top of it at a higher priority.
        /// </para>
        /// <para>
        /// The tier-0 values here and the ones that component pushes come from the
        /// same <see cref="NightAtmosphere"/> table, so a scene with no director in
        /// it still looks like 초저녁 rather than like nothing.
        /// </para>
        /// </summary>
        private static string ConfigureVolumeProfile()
        {
            var profile = AssetDatabase.LoadAssetAtPath<VolumeProfile>(VolumeProfilePath);
            if (profile == null)
            {
                profile = ScriptableObject.CreateInstance<VolumeProfile>();
                AssetDatabase.CreateAsset(profile, VolumeProfilePath);
            }
            else
            {
                // Rebuild in place rather than deleting the asset: the GUID is
                // referenced from Graphics Settings, and a new one there is a
                // silent "no default profile" on someone else's machine.
                foreach (var component in profile.components.ToArray())
                {
                    if (component != null)
                    {
                        AssetDatabase.RemoveObjectFromAsset(component);
                        UnityEngine.Object.DestroyImmediate(component, allowDestroyingAssets: true);
                    }
                }

                profile.components.Clear();
            }

            var night = NightAtmosphere.ForTier(0);

            // Neutral, not ACES. ACES is the safer default for a bright game and
            // the wrong one here: its toe crushes everything below about 2% into
            // identical black, and 2% is where this entire game lives — the whole
            // brief is that a player must read shape *outside* the beam. Neutral
            // keeps the low end separable and still rolls the beam's hot core off
            // instead of clipping it to white.
            var tonemapping = Add<Tonemapping>(profile);
            tonemapping.mode.value = TonemappingMode.Neutral;

            var colour = Add<ColorAdjustments>(profile);
            colour.postExposure.value = night.PostExposure;
            colour.contrast.value = night.Contrast;
            colour.saturation.value = night.Saturation;
            colour.colorFilter.value = new Color(0.90f, 0.95f, 1.0f);

            // §03 hangs the game on a warm torch in a cold building, and that
            // reading only exists if the two are different temperatures. Cooling
            // the whole frame is what makes the unchanged beam read as warm — a
            // cheaper and steadier trick than tinting the light itself, which
            // would tint whatever it hits and lose the contrast at the edges.
            var whiteBalance = Add<WhiteBalance>(profile);
            whiteBalance.temperature.value = night.Temperature;
            whiteBalance.tint.value = -6f;

            // The same idea split by luminance, and this is the override that
            // actually delivers §03's reading. Everything dark goes blue and
            // everything bright goes amber, so the only warm thing on screen is
            // whatever the beam is touching. Doing it here rather than by tinting
            // the flashlight matters: a warm light tints the surface it hits and
            // then the surrounding falloff is warm too, which loses the edge. A
            // luminance split keeps the boundary exactly at the edge of the pool.
            var smh = Add<ShadowsMidtonesHighlights>(profile);
            smh.shadows.value = new Vector4(0.86f, 0.93f, 1.14f, 0f);
            smh.midtones.value = new Vector4(0.98f, 1.0f, 1.04f, 0f);
            smh.highlights.value = new Vector4(1.20f, 1.05f, 0.80f, 0f);
            smh.shadowsStart.value = 0f;
            smh.shadowsEnd.value = 0.30f;
            smh.highlightsStart.value = 0.45f;
            smh.highlightsEnd.value = 1.0f;

            // Restraint on purpose. Bloom exists so the entrance lamp and the beam
            // hitting a wall glow slightly, which is what a real lens does in a
            // dark room; the threshold keeps it off everything else. Overdone
            // bloom in a dark game reads as fog on the lens, and we already have
            // fog. The threshold has to sit below where the graded beam lands or
            // bloom silently does nothing at all — which it did until the exposure
            // was set properly.
            var bloom = Add<Bloom>(profile);
            bloom.threshold.value = 0.55f;
            bloom.intensity.value = 0.65f;
            bloom.scatter.value = 0.68f;
            bloom.tint.value = new Color(1f, 0.95f, 0.88f);
            bloom.highQualityFiltering.value = true;

            var vignette = Add<Vignette>(profile);
            vignette.color.value = Color.black;
            vignette.intensity.value = night.VignetteIntensity;
            vignette.smoothness.value = 0.45f;
            vignette.rounded.value = false;

            // Grain does real work here rather than being a nostalgia filter: an
            // 8-bit frame this dark bands visibly across a fog gradient, and grain
            // dithers the banding away. Response is high so it stays in the
            // shadows and leaves the beam clean.
            var grain = Add<FilmGrain>(profile);
            grain.type.value = FilmGrainLookup.Medium1;
            grain.intensity.value = 0.22f;
            grain.response.value = 0.85f;

            // Small enough to be deniable. §05 puts the player in a helmet-narrow
            // view; a little edge fringing sells a cheap lens. Anything stronger
            // and it reads as a filter someone switched on.
            var aberration = Add<ChromaticAberration>(profile);
            aberration.intensity.value = 0.09f;

            EditorUtility.SetDirty(profile);
            AssetDatabase.SaveAssets();

            AssignDefaultProfile(profile);

            return "grade: " + profile.components.Count + " overrides in " + VolumeProfilePath
                + " (Neutral tonemap, exposure " + night.PostExposure.ToString("0.00")
                + " EV, saturation " + night.Saturation.ToString("0") + ")";
        }

        /// <summary>Adds one override with every parameter live — a default profile is the base state, so nothing in it may be left unset.</summary>
        private static T Add<T>(VolumeProfile profile)
            where T : VolumeComponent
        {
            var component = profile.Add<T>(overrides: true);
            component.name = typeof(T).Name;
            component.hideFlags = HideFlags.HideInHierarchy | HideFlags.HideInInspector;
            AssetDatabase.AddObjectToAsset(component, profile);
            return component;
        }

        private static void AssignDefaultProfile(VolumeProfile profile)
        {
            var settings = GraphicsSettings.GetRenderPipelineSettings<URPDefaultVolumeProfileSettings>();
            if (settings == null)
            {
                Debug.LogWarning("[Atmosphere] URP is not the active pipeline, so the default Volume profile was not assigned.");
                return;
            }

            settings.volumeProfile = profile;

            var globals = GraphicsSettings.GetSettingsForRenderPipeline<UniversalRenderPipeline>();
            if (globals != null)
            {
                EditorUtility.SetDirty(globals);
            }
        }

        // ====================================================================
